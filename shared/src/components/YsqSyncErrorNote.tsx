import { useTr } from '../utils/addressForm';

interface Props {
  variant: 'resume-check' | 'result-save';
  onRetry: () => void;
}

// Тексты живут здесь, а не в пропсах вызывающих: два фронтенда звали
// компонент с одинаковыми длинными строками, и jscpd-храповик честно счёл
// это копипастой. Ярлык кнопки — инфинитив, форма-нейтральный.
const TEXTS = {
  'resume-check': {
    ty: 'Не удалось проверить, есть ли на сервере сохранённый прогресс — если тест уже начат на другом устройстве, сначала попробуй проверить снова, иначе он будет перезаписан.',
    vy: 'Не удалось проверить, есть ли на сервере сохранённый прогресс — если тест уже начат на другом устройстве, сначала попробуйте проверить снова, иначе он будет перезаписан.',
    retryLabel: 'Проверить снова',
  },
  'result-save': {
    ty: 'Результат посчитан и виден только на этом устройстве — отправить его на сервер не получилось. Попробуй ещё раз, чтобы не потерять при смене устройства.',
    vy: 'Результат посчитан и виден только на этом устройстве — отправить его на сервер не получилось. Попробуйте ещё раз, чтобы не потерять при смене устройства.',
    retryLabel: 'Отправить ещё раз',
  },
} as const;

// Баннер сетевого сбоя с кнопкой повтора для теста на схемы — единственная
// копия (правило №3), раньше жила только в schema-miniapp: проверка
// сохранённого на сервере прогресса (YsqIntro) и отправка результата
// (YsqResultView) молчали на сайте (нарушение правила 14 — экран-тупик без
// сигнала). Оба фронтенда рендерят этот компонент напрямую (образец
// CopyFailedHint — useTr берётся из общего контекста, без обёртки на фронт).
export function YsqSyncErrorNote({ variant, onRetry }: Props) {
  const tr = useTr();
  const { ty, vy, retryLabel } = TEXTS[variant];
  return (
    <div style={{ marginBottom: 14 }}>
      <div
        style={{
          fontSize: 12,
          color: 'rgba(255,100,100,0.8)',
          marginBottom: 10,
        }}
      >
        {tr(ty, vy)}
      </div>
      <button
        onClick={onRetry}
        style={{
          width: '100%',
          padding: '11px 0',
          border: 'none',
          borderRadius: 12,
          background: 'rgba(255,100,100,0.12)',
          color: 'var(--accent-red)',
          fontSize: 13,
          fontWeight: 600,
          cursor: 'pointer',
        }}
      >
        {retryLabel}
      </button>
    </div>
  );
}
