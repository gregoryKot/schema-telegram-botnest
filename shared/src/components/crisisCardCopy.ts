// Тексты кризисной карточки в двух ролях. Показ по детекции (crisisMarkers
// нашли маркеры в тексте записи) называет состояние и успокаивает насчёт
// записи. Постоянный блок «Помощь рядом» (standing) видят все без всякой
// детекции — он не «угадывает» состояние и не говорит о записи, которой на
// экране нет. Регрессия 2026-10-03, владелец: «почему это мне сейчас плохо?»
type Tr = (ty: string, vy: string) => string;

export function crisisCardCopy(standing: boolean | undefined, tr: Tr) {
  if (standing) {
    return {
      title: 'Если станет совсем тяжело',
      lead: tr(
        'Можно позвонить на бесплатный телефон доверия — там выслушают, даже если не знаешь, с чего начать:',
        'Можно позвонить на бесплатный телефон доверия — там выслушают, даже если не знаете, с чего начать:',
      ),
      foot: 'Круглосуточно, бесплатно, анонимно.',
    };
  }
  return {
    title: '💛 Похоже, сейчас очень тяжело',
    lead: tr(
      'С этим не нужно справляться в одиночку. Если тяжело прямо сейчас — позвони на бесплатный телефон доверия:',
      'Вы не обязаны справляться с этим в одиночку. Если тяжело прямо сейчас — позвоните на бесплатный телефон доверия:',
    ),
    foot: 'Круглосуточно, бесплатно, анонимно. Запись сохранится как обычно — эта карточка ничего никуда не отправляет.',
  };
}
