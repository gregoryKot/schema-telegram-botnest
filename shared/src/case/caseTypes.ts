/**
 * Разбор одного случая («Что это было») — общие типы потока.
 *
 * Поток заменяет собой три отдельных объяснения: что такое режим, зачем
 * карточка, зачем дневник. Человек за три минуты разбирает один случай и
 * уносит первую запись дневника, половину карточки режима и первую метку на
 * карте себя. Термин приходит после узнавания, а не до него.
 *
 * Печатает человек ровно один раз (сцена) — остальное тапы по чипам: главный
 * барьер для СДВГ-аудитории снимается на входе, а не объясняется.
 *
 * Один источник на оба фронтенда (правило №3): формулировки и логика едины,
 * своя у каждой площадки только разметка.
 */

/** Развод по форме обращения — та же сигнатура, что у остальных билдеров. */
export type Tr = (ty: string, vy: string) => string;

/** Ворота чувств (FEEL_GATES) — вход в разбор, шаг 3 потока. */
export type CaseGateId =
  'fear' | 'sad' | 'anger' | 'shame' | 'drained' | 'unknown' | 'above' | 'ok';

/** Ответы микроопроса-критерия: несоразмерность + невозможность успокоиться. */
export interface CaseCriterionAnswers {
  /** Реакция была крупнее повода? */
  biggerThanCause: boolean | null;
  /** Уговорить себя «ну и ладно» вышло? */
  talkedDown: boolean | null;
}

/** Всё, что человек ответил за разбор. */
export interface CaseAnswers {
  /** Сцена — единственное текстовое поле потока. */
  scene: string;
  /** Была ли сцена начата с готовой рамки (для аналитики и требования детали). */
  sceneFromFrame?: boolean;
  gateId: CaseGateId;
  /** Режим, выбранный на шаге уточнения. */
  modeId: string;
  /** Телесные приметы — до двух чипов. */
  bodyChipIds: string[];
  bodyOwn?: string;
  /** Порывы — до трёх чипов. */
  impulseChipIds: string[];
  impulseOwn?: string;
  criterion: CaseCriterionAnswers;
  /** Имя, которое человек дал части своим словом («Стена»). */
  alias?: string;
}

/** Готовые строки примет — то, что человек видит на экране узнавания. */
export interface CaseTraits {
  /** Ранний сигнал — из телесных чипов. */
  body: string;
  /** Когда приходит — из сцены. */
  trigger: string;
  /** Что тянет сделать — из порывов. */
  impulse: string;
}
