/** Сколько непробельных символов сверх рамки считаются собственной деталью. */
const OWN_DETAIL_THRESHOLD = 10;

const stripSpaces = (value: string): string => value.replace(/\s+/g, '');

/** Длина общего начала двух строк. */
function commonPrefix(a: string, b: string): number {
  const max = Math.min(a.length, b.length);
  let i = 0;
  while (i < max && a[i] === b[i]) i += 1;
  return i;
}

/** Длина общего конца двух строк, не залезающая на уже учтённое начало. */
function commonSuffix(a: string, b: string, taken: number): number {
  const max = Math.min(a.length, b.length) - taken;
  let i = 0;
  while (i < max && a[a.length - 1 - i] === b[b.length - 1 - i]) i += 1;
  return i;
}

/**
 * true, если в сцене есть собственный вклад человека — дописанная деталь или
 * своя сцена вместо рамки. Пустая сцена, слишком короткая сцена и нетронутая
 * рамка вклада не содержат. Рамку не брали (frame пустой) — сцена своя
 * целиком, хватает общей длины.
 */
export function hasOwnDetail(scene: string, frame: string): boolean {
  const s = stripSpaces(scene);
  const f = stripSpaces(frame);
  if (s.length < OWN_DETAIL_THRESHOLD) return false;
  if (f.length === 0) return true;
  const prefix = commonPrefix(s, f);
  const suffix = commonSuffix(s, f, prefix);
  return s.length - prefix - suffix >= OWN_DETAIL_THRESHOLD;
}
