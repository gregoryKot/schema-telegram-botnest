/**
 * Готовые рамки сцены потока «Разбор случая» — старт для тех, у кого свой
 * текст с чистого листа не идёт. Рамка — короткое описание ситуации от
 * третьего лица/безлично, обращения к читателю в ней нет: рамка не про
 * читателя, она про сцену. Человек дописывает к ней свою деталь, и уже эта
 * смесь идёт в карточку режима — не наши слова, а его.
 *
 * hasOwnDetail — гейт кнопки «Дальше» на шаге сцены (правило CLAUDE.md
 * «Никаких хардкод-заглушек» распространяется и на пользовательский ввод,
 * выдаваемый за прожитый случай): без своей детали случай на карте держался
 * бы на наших словах.
 *
 * Считаем не разницу длин и не вхождение подстрокой — оба способа врут на
 * реальных сценариях правки. Разница длин отвергает человека, который стёр
 * рамку и написал своё короче («Мама позвонила, и я замолчала»): он-то как
 * раз написал сцену целиком сам. Вхождение подстрокой ломается от правки
 * внутри рамки — заменил слово, и рамка перестала находиться.
 *
 * Поэтому меряем, сколько символов сцены НЕ объясняются рамкой: отрезаем
 * общее начало и общий конец, остаток и есть вклад человека. Дописал в
 * конец — остаток равен дописанному; стёр рамку и написал своё — остаток
 * равен всей сцене; не тронул рамку — остаток нулевой.
 */
