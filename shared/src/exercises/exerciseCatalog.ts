/** Карточка упражнения по id — для шапок и сроков вне библиотеки. */
export function exerciseCard(id: ExId): ExerciseCard {
  const card = EXERCISES.find((e) => e.id === id);
  if (!card) throw new Error(`exercise ${id} missing from catalog`);
  return card;
}
