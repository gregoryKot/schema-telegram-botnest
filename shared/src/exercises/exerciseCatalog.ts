// библиотеки (идёт по показанному порядку, toolsLayout.arrangeExercises),
// поэтому в шапке упражнения номера нет.
// Имя (title) — тоже отсюда: письмо звалось «Письмо Уязвимому Ребёнку» в библиотеке
// и «Письмо себе» в остальных местах; термин теперь объясняет экран упражнения.

