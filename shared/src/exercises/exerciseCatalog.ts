// Библиотека «Практики» сайта рисует карточки отсюда; шапки экранов
// упражнений, сроки в «Поставить цель», кнопка «Колеса детства» и строка
// «Инструментов» берут те же поля, а не свои копии. До QA 2026-11 (М6)
// длительность жила в четырёх местах и разъехалась: «Письмо» 15–25 мин в
