/** Заголовок строки: у переписанной фразы режима нет, режим вне реестра — «Режим». */
export function warmWordTitle(
  item: Pick<WarmWordsItem, 'source'>,
  modeName: string | undefined,
): string {
  if (item.source === 'phrase') return 'Переписанная фраза';
  return modeName ?? 'Режим';
}

