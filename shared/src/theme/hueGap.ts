// Расстояние между оттенками бумаги по кругу (docs/design/APP_2026-11.md, принцип 2: соседние листы —
// не ближе 40°, пары 25/28 рядом не ставят). Один вход для экрана, который выбирает, стоять ли плитке
// на цветной бумаге рядом с героем (ревью g5 r1: герой глины и плитка теста глины подряд читались одним).

/** Минимальный зазор оттенков соседних листов. */
export const NEIGHBOUR_HUE_GAP = 40;

/** Расстояние по кругу оттенков, 0–180. */
export function hueGap(a: number, b: number): number {
  const d = Math.abs(a - b) % 360;
  return Math.min(d, 360 - d);
}

/** Два листа оттенков ближе зазора соседей подряд читаются одним: плитке теста под героем или герою над первой
 *  группой — белый лист с тенью-слоем своего оттенка. Нет второго листа (null) — не близко. */
export function hueTooNear(
  a: number | null | undefined,
  b: number | null | undefined,
): boolean {
  return a != null && b != null && hueGap(a, b) < NEIGHBOUR_HUE_GAP;
}
