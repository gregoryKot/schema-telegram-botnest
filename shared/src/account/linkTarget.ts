// Кому вообще предлагать объединить аккаунты — и чего именно ему не хватает.
//
// Чистая функция, потому что решение это продуктовое и должно проверяться
// таблицей, а не вычитываться из разметки.
//
// Почему не «у кого один способ входа». Такой признак верен почти для всей
// базы: у большинства пользователей бота второго аккаунта нет и не будет, и
// карточка стала бы постоянным предложением сделать то, что им не нужно
// (правило про одно очевидное действие на экран). Предлагаем там, где второй
// аккаунт РЕАЛЬНО мешает:
//
//   - на сайте у человека, который вошёл только почтой/Google/VK: его записи
//     из бота и мини-аппа лежат отдельно, и другого пути их собрать нет;
//   - в MAX — там своего входа для сайтов нет вовсе;
//   - в Telegram-мини-аппе автопоказа НЕТ: у человека есть обычный вход на
//     сайте, и предлагать всем подряд незачем. Там карточка раскрывается по
//     явному жесту («у меня уже есть аккаунт»), см. параметр `asked`.

export type LinkTarget = 'telegram' | 'site' | null;

/** Входы, которые дают аккаунт в мессенджере. */
export const MESSENGER_PROVIDERS = ['telegram', 'max'];

export interface LinkTargetInput {
  /** Провайдеры текущего аккаунта: 'google' | 'telegram' | 'max' | … */
  providers: string[] | null;
  hostId: string;
  /** Человек сам попросил показать привязку (жест в Telegram-мини-аппе). */
  asked?: boolean;
}

/**
 * `null` — карточку не показываем. Про `providers === null` (ответ сервера не
 * пришёл) тоже `null`: предлагать «подключи» тому, про кого мы ничего не
 * знаем, значит показывать выдуманное состояние.
 */
export function missingLinkTarget({
  providers,
  hostId,
  asked = false,
}: LinkTargetInput): LinkTarget {
  // Пустой список — тоже «ничего не знаем»: у вошедшего человека провайдер
  // есть по определению, значит это сбой чтения, а не состояние аккаунта.
  if (!providers || providers.length === 0) return null;
  const hasMessenger = providers.some((p) => MESSENGER_PROVIDERS.includes(p));
  const hasSite = providers.some((p) => !MESSENGER_PROVIDERS.includes(p));

  if (hostId === 'web') {
    // Уже есть мессенджер — собирать нечего.
    return hasMessenger ? null : 'telegram';
  }
  // Внутри мессенджера предлагаем подтянуть данные с сайта.
  if (hasSite) return null;
  if (hostId === 'max') return 'site';
  return asked ? 'site' : null;
}
