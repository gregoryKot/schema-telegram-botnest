// Тексты карточки объединения аккаунтов — отдельно от разметки: так они
// читаются целиком, правятся целиком и проходят гейты голоса одним файлом.
//
// Все строки с обращением живут ВНУТРИ tr() (правило проекта): имя параметра
// обязано остаться ровно `tr` — на него настроено вырезание в гейтах
// check-second-person и check-address-form. Прошедшего времени и кратких
// прилагательных нет: род читателя нам неизвестен и заводить его не надо.
import type { LinkTarget } from './linkTarget';

export type Tr = (ty: string, vy: string) => string;

export interface AccountLinkCopy {
  title: string;
  /** Что это и откуда — до первого действия человека. */
  what: string;
  /** Что произойдёт после нажатия. */
  next: string;
  action: string;
  waiting: string;
}

export function buildAccountLinkText(
  tr: Tr,
  target: Exclude<LinkTarget, null>,
): AccountLinkCopy {
  if (target === 'telegram') {
    return {
      title: 'Данные из Telegram',
      what: tr(
        'В боте и мини-аппе Telegram записи лежат под отдельным входом — с этим аккаунтом они пока не связаны. Подключи Telegram, и оценки, дневники и упражнения соберутся в одном месте.',
        'В боте и мини-аппе Telegram записи лежат под отдельным входом — с этим аккаунтом они пока не связаны. Подключите Telegram, и оценки, дневники и упражнения соберутся в одном месте.',
      ),
      next: tr(
        'Нажмёшь — откроется бот и спросит, точно ли это ты. Подтвердишь там, и всё окажется вместе.',
        'Нажмёте — откроется бот и спросит, точно ли это вы. Подтвердите там, и всё окажется вместе.',
      ),
      action: 'Подключить Telegram',
      waiting: tr(
        'Открылся Telegram — бот показывает код. Сверь его с кодом ниже и подтверди, что это ты.',
        'Открылся Telegram — бот показывает код. Сверьте его с кодом ниже и подтвердите, что это вы.',
      ),
    };
  }
  return {
    title: 'Данные с сайта',
    what: tr(
      'Если этот же дневник есть у тебя на сайте, здесь он пока отдельный. Подключи сайт — записи, оценки и упражнения окажутся в одном аккаунте.',
      'Если этот же дневник есть у вас на сайте, здесь он пока отдельный. Подключите сайт — записи, оценки и упражнения окажутся в одном аккаунте.',
    ),
    next: tr(
      'Нажмёшь — откроется браузер: войди там тем способом, которым обычно заходишь, и подтверди перенос.',
      'Нажмёте — откроется браузер: войдите там тем способом, которым обычно заходите, и подтвердите перенос.',
    ),
    action: 'У меня уже есть аккаунт',
    waiting: tr(
      'Открылся браузер — войди там тем способом, которым обычно заходишь. Код ниже нужен, только если браузер не открылся.',
      'Открылся браузер — войдите там тем способом, которым обычно заходите. Код ниже нужен, только если браузер не открылся.',
    ),
  };
}

