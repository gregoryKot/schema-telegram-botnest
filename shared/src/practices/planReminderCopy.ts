// Тексты планов о напоминании (U5, аудит 2026-11): уведомления уходят только
// в Telegram, а человек с Google, почтой или MAX видел «напомним» и выбирал
// час — напоминание не приходило. Обещание звучит, только когда сервер
// ответил, что напоминанию есть куда прийти (`notifyReachable`); иначе —
// честная строка и календарь (PlanConfirm, NeedTodaySheet, PlansScreen).
import type { Tr } from '../needs/types';

/** Подпись карточки «Запланировать шаг на завтра» в листе потребности. */
export const planStepHint = (reachable: boolean | null): string =>
  reachable === true
    ? 'Один маленький шаг – и напомним'
    : 'Один маленький шаг – можно поставить в календарь';

/** Лист плана без канала: почему напоминания не будет и что вместо него. */
export const planNoReminderNote = (tr: Tr): string =>
  tr(
    'Напоминания приходят в Telegram — у тебя он не подключён. Поставь шаг в календарь: напомнит он.',
    'Напоминания приходят в Telegram — у вас он не подключён. Поставьте шаг в календарь: напомнит он.',
  );
