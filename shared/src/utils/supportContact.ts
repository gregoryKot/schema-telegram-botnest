// Адрес поддержки — одной копией на оба фронтенда и на все площадки.
//
// Экран «Не удалось войти» звал «напиши нам» и на этом заканчивался: кто «мы»
// и куда писать — человеку с телефоном в руках неизвестно. Обещание помощи
// без адреса оставляет тот же тупик, из которого пробовали вывести.
//
// Площадка решает, какой адрес показать. Телеграмная ссылка внутри MAX — это
// второй тупик подряд: Telegram у человека может быть не установлен, а MAX
// открывает внешние ссылки в браузере, где t.me показывает страницу-заглушку.
// Почта работает откуда угодно и читается даже там, где ссылка не нажимается.
import type { HostId } from '../host/types';

/** Автор проекта в Telegram — тот же контакт, что в «О приложении». */
const AUTHOR_TG = { url: 'https://t.me/kotlarewski', label: '@kotlarewski' };
/** Почта оператора — та же, что в оферте и политике конфиденциальности. */
const AUTHOR_EMAIL = {
  url: 'mailto:gregorykot@gmail.com',
  label: 'gregorykot@gmail.com',
};

export interface SupportContact {
  /** Куда ведёт ссылка. */
  url: string;
  /** Что видно на экране: сам адрес, а не «нам» — видно, кому пишешь. */
  label: string;
}

export function supportContact(hostId: HostId | undefined): SupportContact {
  return hostId === 'max' ? AUTHOR_EMAIL : AUTHOR_TG;
}
