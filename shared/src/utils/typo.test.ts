// Неразрывные пробелы при отрисовке (typo.ts — лендинг и листы приложения): тире не начинает строку,
// короткое слово не висит в конце строки, короткое название в кавычках не рвётся; слова не меняются.
// Тексты самого лендинга — webapp/src/pages/landing/glueContent.test.ts.
import { describe, it, expect } from 'vitest';
import { glue } from './typo';

const NB = '\u00a0';
const NBH = '\u2011';

describe('glue: неразрывные пробелы', () => {
  it('пробел перед « — » неразрывный, после — обычный', () => {
    expect(glue('Первый шаг — просто заметить')).toBe(
      `Первый шаг${NB}— просто заметить`,
    );
  });

  it('после предлога, союза и числа пробел неразрывный; после длинного слова — обычный', () => {
    expect(glue('бережно, в вашем темпе')).toBe(`бережно, в${NB}вашем темпе`);
    expect(glue('бесплатно · без рекламы')).toBe(
      `бесплатно${NB}· без${NB}рекламы`,
    );
    expect(glue('встреча 15 минут')).toBe(`встреча 15${NB}минут`);
    expect(glue('тревога и самокритика')).toBe(`тревога и${NB}самокритика`);
    // после знака препинания перенос разрешён: «а,» — уже не висячий союз
    expect(glue('а, может')).toBe('а, может');
  });

  it('точка-разделитель не начинает строку; «схема-терапия» не рвётся на дефисе', () => {
    expect(glue('схема-терапия · частная практика')).toBe(
      `схема${NBH}терапия${NB}· частная практика`,
    );
    expect(glue('Схема-терапии и КПТ')).toBe(`Схема${NBH}терапии и${NB}КПТ`);
    // другие слова с дефисом не трогаем: перенос по дефису там законный
    expect(glue('кто-то рядом')).toBe('кто-то рядом');
    // число в скобках держится со словом: «(116 вопросов)» не рвётся после «(116»
    expect(glue('опросник (116 вопросов)')).toBe(`опросник (116${NB}вопросов)`);
  });

  it('цепочка коротких слов склеивается целиком, без пропусков', () => {
    expect(glue('и в вашем')).toBe(`и${NB}в${NB}вашем`);
  });

  it('короткое название в кавычках — одной строкой, длинная цитата — нет', () => {
    expect(glue('«Всё по схеме» — бесплатное')).toBe(
      `«Всё${NB}по${NB}схеме»${NB}— бесплатное`,
    );
    expect(glue('к «какая схема включилась»')).toBe(
      `к${NB}«какая схема включилась»`,
    );
  });

  // Ревью g1: на телефоне «Зачем это всё» висели «со / временем», «с / него», «в / дневнике».
  it('предлоги «с», «со», «в» в текстах листов не висят в конце строки', () => {
    expect(glue('в одну картину: со временем видно')).toBe(
      `в${NB}одну картину: со${NB}временем видно`,
    );
    expect(glue('и закрутился: с него начинается разбор')).toBe(
      `и${NB}закрутился: с${NB}него начинается разбор`,
    );
    expect(glue('на место: запись в дневнике.')).toBe(
      `на${NB}место: запись в${NB}дневнике.`,
    );
  });
});
