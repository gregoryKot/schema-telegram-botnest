/**
 * Пословный свип на остаточные «ты»-формы — для тестов «вы»-режима (правило
 * обращения ты/вы в CLAUDE.md). Ищет местоимения (ты/тебя/тебе/тобой),
 * притяжательные (твой/…) и глагольные окончания 2 л. ед. ч. (-ешь/-ишь).
 *
 * Разбор на слова вместо \b-регэкспа: \b в JS не считает кириллицу буквами,
 * и «граница слова» вокруг «ты» не находится — \bты\b молча пропускал бы всё.
 */
export function hasTyForms(text: string): boolean {
  const words = text.toLowerCase().match(/[а-яё]+/gu) ?? [];
  return words.some(
    (w) =>
      /^(ты|теб[еяё]|тобой|тво(й|я|ё|е|и|его|ей|им|ём|их))$/.test(w) ||
      /(аешь|яешь|уешь|юешь|ишь|ешь)$/.test(w),
  );
}
