/**
 * Где начинается серия одинаковых ключей подряд: `true` у первого элемента серии. Знак сущности рисуется
 * только у него, у соседей той же серии — чистая бумага или отступ (ревью g5 r2: три плитки Критика подряд с
 * одним знаком в чек-ине режима, два одинаковых знака домена подряд в «Выраженных схемах» читались штампом).
 */
export function runStarts<T>(keys: readonly T[]): boolean[] {
  return keys.map((k, i) => i === 0 || keys[i - 1] !== k);
}
