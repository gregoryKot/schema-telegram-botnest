// Кризисная детекция (правило №7 CLAUDE.md: свободный текст = кризисный
// путь). Полнота важнее точности — пропуск реального кризисного текста
// катастрофичен, ложное срабатывание дёшево (просто карточка с телефоном
// доверия). Файл парный (webapp/schema-miniapp реэкспортируют этот модуль),
// поэтому кейсы здесь — единственная копия, дающая покрытие самому shared.
import { describe, it, expect } from 'vitest';
import { detectCrisis, detectCrisisAny } from './crisisMarkers';

describe('detectCrisis — срабатывает', () => {
  it.each([
    'думаю о суициде',
    'хочу убить себя',
    'хочется покончить с собой',
    'больше не хочу жить',
    'незачем жить',
    'просто хочу умереть',
    'думала повеситься',
    'хотел вскрыть вены',
    'наглотаюсь таблеток и всё',
    'занимаюсь самоповреждением',
    'селфхарм вернулся',
    'self-harm опять',
    'снова режу себя',
    'хочу спрыгнуть с крыши',
    'хочу исчезнуть',
    'выбросилась из окна', // прошедшее время, ж.р.
    'покончил с собой', // прошедшее время, м.р.
    'нехочу жить', // слитное написание
    'хочу выпилиться', // жаргонный эвфемизм, возвратная форма
  ])('«%s»', (text) => {
    expect(detectCrisis(text)).toBe(true);
  });

  it('не зависит от регистра и ё/е', () => {
    expect(detectCrisis('НЕ ХОЧУ ЖИТЬ')).toBe(true);
    expect(detectCrisis('хочется покончить с собоЙ')).toBe(true);
  });

  it('латинские гомоглифы (визуальная маскировка) тоже ловятся', () => {
    expect(detectCrisis('cуицид не отпускает')).toBe(true); // латинская c
    expect(detectCrisis('думаю о cамоубийстве')).toBe(true);
  });
});

describe('detectCrisis — НЕ срабатывает (словарная точность)', () => {
  it.each([
    'сегодня хороший день, гулял в парке',
    'хочу убить время до встречи',
    'умираю со смеху над этим сериалом',
    'порезал хлеб и приготовил ужин',
    'страх смерти преследует меня с детства',
    'вены на руке проступают, когда мерзну',
    'хочу выпилить старое дерево в саду', // созвучно эвфемизму, но бытовая фраза
  ])('«%s»', (text) => {
    expect(detectCrisis(text)).toBe(false);
  });

  it('пустые/отсутствующие значения — false, не падение', () => {
    expect(detectCrisis('')).toBe(false);
    expect(detectCrisis(null)).toBe(false);
    expect(detectCrisis(undefined)).toBe(false);
  });
});

describe('detectCrisisAny', () => {
  it('находит маркер в любом из нескольких полей формы', () => {
    expect(detectCrisisAny('обычный текст', '', 'не хочу жить')).toBe(true);
  });

  it('ни в одном поле маркера нет — false', () => {
    expect(detectCrisisAny('обычный текст', null, undefined)).toBe(false);
  });

  it('без единого аргумента — false (не падает на пустом вызове)', () => {
    expect(detectCrisisAny()).toBe(false);
  });
});
