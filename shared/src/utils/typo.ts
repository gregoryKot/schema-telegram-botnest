// Неразрывные пробелы — при отрисовке, а не в контенте (одна механика на лендинг и листы приложения:
// «Зачем это всё», WhyThree, легенда знаков): текст src/articles/home-landing.content.ts общий с HTML
// для робота (home-seo.render.ts), и слова там не меняются. Что держим вместе:
//  • тире (— и –) и точка-разделитель не начинают строку — пробел перед ними неразрывный;
//  • «схема-терапия», «4-4-6», «кто-то», «по-настоящему» не рвутся на дефисе — дефис неразрывный
//    (U+2011): подход, короткие числа (не телефон и не дата), частицы -то/-либо/-нибудь/-ка и «по-»;
//    остальные слова с дефисом переносятся как обычно; диапазон «3–5» держится связкой U+2060;
//  • короткий предлог, союз или число не висят в конце строки («в вашем», «без рекламы»,
//    «15 минут») — пробел после них неразрывный;
//  • короткое название в кавычках не рвётся посередине («Всё по схеме», «за рулём»):
//    до 14 знаков внутри «…», длинная цитата переносится как обычно.
// Регулярок с lookbehind нет: старый Safari на iOS < 16.4 падает на них при разборе модуля.
const NBSP = '\u00a0';
/** Слово, после которого пробел неразрывный: 1–2 буквы, короткий предлог, число (и «~10», «≈2»). */
const SHORT = /^[«("]?(?:[а-яё]{1,2}|без|для|про|при|под|над|[~≈]?\d+)$/i;
/** Короткое название в кавычках — целиком на одной строке. */
const SHORT_QUOTE = /«[^«»]{1,14}»/g;
/** Знаки, которые не начинают строку: тире (длинное и короткое) и точка-разделитель. */
const NO_START = new Set(['—', '–', '·']);
/** Неразрывный дефис и связка без пробела (word joiner: диапазон «3–5» держится целиком). */
const [NBHY, WJ] = ['\u2011', '\u2060'];
/** Короткие числа через дефис («4-4-6», «5-6», «10-15») — вместе; телефон 8-800-…, дата 2026-11-09 — как есть. */
const SHORT_NUMS = /^(?:\d{1,2}-\d{1,2}|\d(?:-\d)+)$/;
const nums = (m: string) => (SHORT_NUMS.test(m) ? m.replace(/-/g, NBHY) : m);
/** Дефис, на котором строка не рвётся: подход, короткие числа, частицы, «по-». */
function keepHyphens(text: string): string {
  return text
    .replace(/(схема)-(терапи)/gi, `$1${NBHY}$2`)
    .replace(/\d+(?:-\d+)+/g, nums)
    .replace(/(\d)–(?=\d)/g, `$1${WJ}–${WJ}`)
    .replace(/([а-яё])-(то|либо|нибудь|ка)(?![а-яё])/gi, `$1${NBHY}$2`)
    .replace(/(^|[\s«("])(по)-(?=[а-яё])/gi, `$1$2${NBHY}`);
}

/** Пробелы: неразрывный перед тире и «·» и после короткого слова (с новой строки — по ней); знаки как есть. */
function glueWords(text: string): string {
  const ws = text.split(' ');
  const keep = (i: number) =>
    NO_START.has(ws[i]) || SHORT.test(ws[i - 1].split('\n').pop() ?? '');
  return ws.reduce((out, w, i) => out + (keep(i) ? NBSP : ' ') + w);
}

export function glue(text: string): string {
  const quoted = text.replace(SHORT_QUOTE, (q) => q.replace(/ /g, NBSP));
  return glueWords(keepHyphens(quoted));
}

/** Текст, который ввёл сам человек (запись дневника, заметка): только пробелы glueWords — дефисы, тире и цифры
 *  его, без U+2011 и U+2060: скопированная запись приходит теми же знаками, поиск «кто-то» её находит (g3 r5). */
export const glueSpaces = glueWords;

/** Проп, который бывает и не строкой (ReactNode): строку склеивает, остальное (JSX, число) отдаёт как есть.
 *  Одна функция у g2 и g3 (APP_2026-11.md, «Сведение с g2»): EntitySheet, DoneSheet, шаг мастера клеят сами. */
export const glueIf = <T>(text: T): T | string =>
  typeof text === 'string' ? glue(text) : text;
