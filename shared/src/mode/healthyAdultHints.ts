/**
 * Подсказки Здорового Взрослого для шага «голос Здорового Взрослого».
 *
 * Приоритет: точная фраза из карточки режима (modeCards/) → подсказка по
 * функциональной семье (modeTest.ts) → нейтральный дефолт. Тон — тёплая
 * самоподдержка от 1-го лица («я …»), поэтому form-agnostic (правило
 * обращения: 1-е лицо не разводится).
 */
import { findTestGroupByModeId } from './modeTest';
import { getModeCard } from './modeCards';

const HINTS: Record<string, string> = {
  hurt: 'Мне сейчас больно, и это по-настоящему. Я не один, и это можно пережить — шаг за шагом. Я имею право на заботу и тепло.',
  anger:
    'Моя злость — сигнал, что нарушено что-то важное. Я имею право злиться и право сказать об этом словами, не разрушая себя и других.',
  avoid:
    'Я отгородился, чтобы не было больно, — это можно понять. Сейчас я в безопасности, и можно потихоньку вернуться к себе и к чувствам.',
  surrender:
    'Мои желания и границы тоже важны. Я имею право на «нет». Даже маленький выбор в свою сторону — уже забота о себе.',
  control:
    'Мне не нужно держать под контролем всё. Часть вещей мне неподвластна — и это выносимо. Можно ослабить хватку и выдохнуть.',
  grandiose:
    'Мне не нужно быть выше других, чтобы быть ценным. Я ценен и без брони — можно позволить себе быть живым и уязвимым.',
  critic:
    'Этот жёсткий голос — не факт и не я сам. Ошибаться — по-человечески. Я отнесусь к себе так же бережно, как к близкому другу.',
  ok: 'Мне сейчас спокойно, и это моя опора. Я запомню это состояние — к нему можно возвращаться, когда снова станет трудно.',
};

export const DEFAULT_HINT =
  'Я могу отнестись к себе бережно — как к близкому другу в трудный момент. Мне можно то, что я сейчас чувствую.';

/** Голос Здорового Взрослого: сперва карточка режима, потом семья теста. */
export function healthyAdultHint(modeId: string): string {
  const card = getModeCard(modeId)?.healthyAdult;
  if (card) return card;
  const group = findTestGroupByModeId(modeId);
  return (group && HINTS[group.id]) || DEFAULT_HINT;
}
