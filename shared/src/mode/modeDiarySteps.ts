/**
 * Шаги дневника режимов — вопрос = отдельный экран визарда (после выбора
 * режима). Один источник для обоих фронтов (правило №3): формулировки и
 * примеры едины. Тон — тёплый схема-терапевт; примеры конкретны, чтобы было
 * понятно, что писать (правило онбординга: «откуда и зачем»).
 *
 * Обязательна только ситуация. Остальное можно пропустить — низкий порог
 * входа для СДВГ: можно сохранить в пару шагов или пройти глубже.
 *
 * `example` подставляется плейсхолдером — исчезает при вводе, не выдаётся за
 * сохранённые данные (не заглушка).
 */

type Tr = (ty: string, vy: string) => string;

/** Порядок = порядок шагов визарда; единый источник имён полей дневника. */
export const MODE_DIARY_FIELD_KEYS = [
  'situation',
  'thoughts',
  'feelings',
  'bodyFeelings',
  'actions',
  'actualNeed',
  'childhoodMemories',
] as const;

export type ModeDiaryFieldKey = (typeof MODE_DIARY_FIELD_KEYS)[number];

/**
 * Что сохраняет дневник режимов — общий тип для `onSave` в обоих фронтах
 * (правило №3: одинаковая форма данных, не копипастить интерфейс). Обязательны
 * только modeId + situation, остальное — опционально (можно пропустить шаг).
 */
export interface ModeEntrySaveData {
  modeId: string;
  situation: string;
  thoughts?: string;
  feelings?: string;
  bodyFeelings?: string;
  actions?: string;
  actualNeed?: string;
  childhoodMemories?: string;
  healthyResponse?: string;
}

export interface ModeDiaryStep {
  key: ModeDiaryFieldKey;
  /** тёплый вопрос-заголовок шага */
  title: string;
  /** мягкая подсказка под заголовком */
  hint: string;
  /** конкретный пример ответа (плейсхолдер) */
  example: string;
  /** обязательное поле (только ситуация) */
  required?: boolean;
  rows?: number;
}

