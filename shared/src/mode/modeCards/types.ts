/**
 * Содержательный «портрет режима» — единый источник для всех 35 режимов
 * схема-терапии (см. MODE_GROUPS в schema-miniapp/src/schemaTherapyData.ts).
 *
 * До этого файла про режим существовала одна строка (`short`) — экран
 * «Знакомство с режимом» (ModeIntroSheet) показывал её и пять пустых полей
 * для заполнения клиентом. ModeCard — не замена этих полей (клиент всё равно
 * описывает свой личный опыт), а готовый ориентир и опора, на который экран
 * может сослаться, если клиенту трудно начать с чистого листа.
 *
 * ВАЖНО (правило обращения, CLAUDE.md): всё содержимое form-agnostic —
 * безличные/номинативные описания в третьем лице, без обращения ко второму
 * лицу (ед. и мн. число, включая притяжательные формы). Только `voice` и
 * `healthyAdult` — прямая речь от 1-го лица («я …») — это тоже form-agnostic
 * и разводить не нужно.
 */
export interface ModeCard {
  /** Развёрнутое описание режима, 1–2 предложения (аналог libraryDesc у схем). */
  about: string;
  /** Что включает режим — типичные триггеры. Перечисление через «;». */
  triggers: string;
  /** Как узнаётся в теле и чувствах — телесные ощущения + эмоции. */
  body: string;
  /** Голос режима — прямая речь в кавычках-ёлочках, 1–2 короткие фразы от 1-го лица. */
  voice: string;
  /** Что режим делает — наблюдаемое поведение. */
  behavior: string;
  /**
   * Зачем появился — какую задачу он когда-то решал (режим — не поломка, а
   * бывшее решение). Для здоровых режимов (happy_child/healthy_adult/
   * good_parent) — что его питает и укрепляет.
   */
  origin: string;
  /**
   * Чего стоит сейчас — цена режима. Для здоровых режимов — что мешает ему
   * включаться (усталость, спешка, отсутствие практики).
   */
  cost: string;
  /** Какая потребность стоит под режимом. */
  need: string;
  /** Голос Здорового Взрослого этому режиму — прямая речь от 1-го лица. */
  healthyAdult: string;
}
