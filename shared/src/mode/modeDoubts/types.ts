/**
 * Пара «с чем путают режим» — соседние режимы, которые новичок легко
 * принимает один за другой. Данные для кнопки сравнения выбранного режима
 * с похожими (карточка выбранного режима, ModeSelectStep/ModeEntryForm).
 *
 * Пары симметричны: показываются из карточки обоих режимов (getDoubtsForMode
 * в index.ts разворачивает симметрию — a↔b видно и со стороны a, и со стороны b).
 *
 * ВАЖНО (правило обращения, CLAUDE.md): gist/check form-agnostic — безличные
 * обороты и инфинитивы («спросить себя», «заметить»), без обращения ко
 * второму лицу — разводить по формам обращения не нужно.
 */
export interface ModeDoubtPair {
  /** id первого режима пары (MODE_GROUPS.items[].id). */
  a: string;
  /** id второго режима пары. */
  b: string;
  /** Суть различия, 1–2 предложения. */
  gist: string;
  /** Быстрая проверка «в моменте» — как отличить одно от другого. */
  check: string;
}
