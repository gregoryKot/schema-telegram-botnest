/**
 * Взаимные пояснения «откуда это и зачем» для двух соседних механик режимов
 * (правило онбординга CLAUDE.md — до первого действия пользователь должен
 * понимать, что это за экран и зачем он нужен):
 *
 * - «Знакомство с режимом» (ModeIntroSheet/FlashcardEx ModeEx) — карточка-
 *   портрет режима, заполняется один раз и остаётся в «Моих заметках»;
 * - «Дневник режимов» (ModeEntrySheet/ModeEntryForm) — запись про конкретный
 *   момент, таких записей может быть много.
 *
 * Каждый экран отсылает к другому, чтобы не путать «портрет» и «случай».
 * Один источник для обоих фронтов (правило №3).
 *
 * Различие идёт первой строкой и одной фразой: «Дневник — про вчерашний
 * вечер. Карточка — про все такие вечера сразу». Прежние формулировки
 * объясняли разницу через названия разделов («разбор случая — в Дневнике
 * режимов»), то есть требовали уже знать, что это за разделы. Человеку,
 * который впервые видит обе кнопки, такое объяснение не помогает — он и
 * спрашивает, чем одно отличается от другого.
 */

type Tr = (ty: string, vy: string) => string;

/** Пояснение под «Знакомство с режимом» (карточка-портрет режима). */
export function buildModeIntroExplainer(tr: Tr): string {
  return tr(
    'Дневник — про вчерашний вечер. Карточка — про все такие вечера сразу: как режим звучит, по чему узнаётся, что заставляет делать. Собери приметы один раз — дальше режим узнаётся за секунду, а не задним числом.',
    'Дневник — про вчерашний вечер. Карточка — про все такие вечера сразу: как режим звучит, по чему узнаётся, что заставляет делать. Соберите приметы один раз — дальше режим узнаётся за секунду, а не задним числом.',
  );
}

/** Пояснение под «Дневник режимов» (запись про конкретный момент). */
export function buildModeDiaryExplainer(tr: Tr): string {
  return tr(
    'Дневник — про вчерашний вечер. Записей будет много, и каждая про один момент. Через три-пять случаев видно, что запускает режим и чего тебе в такие моменты не хватает.',
    'Дневник — про вчерашний вечер. Записей будет много, и каждая про один момент. Через три-пять случаев видно, что запускает режим и чего вам в такие моменты не хватает.',
  );
}
