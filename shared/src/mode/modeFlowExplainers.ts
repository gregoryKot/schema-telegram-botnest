/**
 * Взаимные пояснения «откуда это и зачем» для двух соседних механик режимов
 * (правило онбординга CLAUDE.md — до первого действия пользователь должен
 * понимать, что это за экран и зачем он нужен):
 *
 * - «Знакомство с режимом» (ModeIntroSheet/FlashcardEx ModeEx) — карточка-
 *   портрет режима, заполняется один раз и остаётся в «Моих заметках»;
 * - «Дневник режимов» (ModeEntrySheet/ModeEntryForm) — запись про конкретный
 *   момент, таких записей может быть много.
 *
 * Каждый экран отсылает к другому, чтобы не путать «портрет» и «случай».
 * Один источник для обоих фронтов (правило №3).
 */

type Tr = (ty: string, vy: string) => string;

/** Пояснение под «Знакомство с режимом» (карточка-портрет режима). */
export function buildModeIntroExplainer(tr: Tr): string {
  return tr(
    'Это карточка-портрет режима — какой он у тебя. Заполни один раз, дополняй при желании — она останется в «Моих заметках», а разбор конкретного случая, когда режим включился, — в «Дневнике режимов».',
    'Это карточка-портрет режима — какой он у вас. Заполните один раз, дополняйте при желании — она останется в «Моих заметках», а разбор конкретного случая, когда режим включился, — в «Дневнике режимов».',
  );
}

/** Пояснение под «Дневник режимов» (запись про конкретный момент). */
export function buildModeDiaryExplainer(tr: Tr): string {
  return tr(
    'Это запись про один конкретный момент — что было с тобой, когда режим включился. Записей будет много, а общий портрет режима — в карточке «Знакомство с режимом».',
    'Это запись про один конкретный момент — что было с вами, когда режим включился. Записей будет много, а общий портрет режима — в карточке «Знакомство с режимом».',
  );
}
