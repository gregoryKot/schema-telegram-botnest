/**
 * Взаимные пояснения «откуда это и зачем» для двух соседних механик схем
 * (правило онбординга CLAUDE.md — до первого действия пользователь должен
 * понимать, что это за экран и зачем он нужен):
 *
 * - «Знакомство со схемой» (SchemaIntroSheet/FlashcardEx SchemaEx) — карточка-
 *   портрет схемы, заполняется один раз и остаётся в «Моих заметках»;
 * - «Дневник схем» (SchemaEntrySheet) — запись про конкретный момент, когда
 *   схема включилась, таких записей может быть много.
 *
 * Каждый экран отсылает к другому, чтобы не путать «портрет» и «случай».
 * Один источник для обоих фронтов (правило №3). Структура/тон — как в
 * shared/src/mode/modeFlowExplainers.ts (единый визуальный язык, PR #187).
 */

type Tr = (ty: string, vy: string) => string;

/** Пояснение под «Знакомство со схемой» (карточка-портрет схемы). */
export function buildSchemaIntroExplainer(tr: Tr): string {
  return tr(
    'Это карточка-портрет схемы — какая она у тебя. Заполни один раз, дополняй при желании — она останется в «Моих заметках», а разбор конкретного случая, когда схема включилась, — в «Дневнике схем».',
    'Это карточка-портрет схемы — какая она у вас. Заполните один раз, дополняйте при желании — она останется в «Моих заметках», а разбор конкретного случая, когда схема включилась, — в «Дневнике схем».',
  );
}

/** Пояснение под «Дневник схем» (запись про конкретный момент). */
export function buildSchemaDiaryExplainer(tr: Tr): string {
  return tr(
    'Это запись про один конкретный момент — что случилось и какие твои схемы включились. Записей будет много, а общий портрет схемы — в карточке «Знакомство со схемой».',
    'Это запись про один конкретный момент — что случилось и какие ваши схемы включились. Записей будет много, а общий портрет схемы — в карточке «Знакомство со схемой».',
  );
}
