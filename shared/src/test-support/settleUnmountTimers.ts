// Общий кусок rtlCleanup.ts всех трёх фронтовых пакетов. Сам rtlCleanup не
// общий: у каждого пакета свой экземпляр RTL (см. его шапку). По той же
// причине здесь нет импорта vitest: признак поддельных таймеров пакет
// передаёт из своего экземпляра.

/**
 * Даёт сработать таймерам, которые компонент ставит при размонтировании
 * (tiptap: `scheduleDestroy` через `setTimeout(…, 1)`), пока jsdom ещё жив.
 * Таймеры с одной задержкой Node запускает в порядке постановки, поэтому
 * ожидание ≥ 1 мс после размонтирования пропускает их вперёд. С поддельными
 * таймерами ждать нечего и нельзя: такие после сноса окружения не сработают,
 * а поддельный setTimeout здесь повис бы.
 */
export async function settleUnmountTimers(
  isFakeTimers: () => boolean,
  ms = 10,
): Promise<void> {
  if (isFakeTimers()) return;
  await new Promise((resolve) => setTimeout(resolve, ms));
}
