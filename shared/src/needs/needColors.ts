/**
 * Цвет пяти базовых потребностей — один источник на оба фронтенда.
 *
 * До отказа от эмодзи потребность узнавали по картинке (🤝, 🕊, 🎨…), а цвет
 * был оформлением графика. Теперь наоборот: картинки нет, и цвет стал
 * опознавательным знаком — точка рядом с названием, полоса в графике,
 * заливка в колесе. Раз он несёт смысл, копий у него быть не может: до этого
 * палитра лежала в четырёх файлах (по два в каждом фронтенде), и они уже
 * начали расходиться.
 *
 * Цвет — не единственный носитель: рядом всегда есть название потребности,
 * иначе экран не читался бы при цветовой слепоте.
 */
export const NEED_COLORS: Record<string, string> = {
  attachment: '#ff6b9d',
  autonomy: '#4fa3f7',
  expression: '#facc15',
  play: '#06d6a0',
  limits: '#a78bfa',
};

/** Порядок потребностей — совпадает с NEED_ORDER контент-реестров. */
export const NEED_COLOR_ORDER = [
  'attachment',
  'autonomy',
  'expression',
  'play',
  'limits',
] as const;

/**
 * Цвет потребности с нейтральным фолбэком: неизвестный id не должен красить
 * строку в чужой цвет — лучше приглушённый серый токен.
 */
export function needColor(id: string): string {
  return NEED_COLORS[id] ?? 'var(--muted)';
}
