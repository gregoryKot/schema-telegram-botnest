// Рубрика плана для пункта «Что делать» листа схемы: пункты — разные по смыслу действия, и в план каждый
// ложится в свой канал метода. Подбор — подсказка: лист «В план» показывает рубрику и даёт сменить.
import type { GuideChannel, PlanRubric } from './planItem';

/** Корни слов канала; порядок каналов решает ничью (отношения названы прямо реже всех — им первое слово). */
const CHANNEL_STEMS: readonly (readonly [GuideChannel, RegExp])[] = [
  [
    'relationship',
    /репарентинг|конфронтац|в отношениях с терапевт|терапевтическ\S* отношен|терапевт (?:сам|называет|говорит|признаёт|показывает|остаётся|выдерживает|не )|самораскрыти|на сессии и между/giu,
  ],
  [
    'experiential',
    /рескриптинг|в образ|воображ|стуль|стула|письм[оа] |горева|оплак|прожи(?:ть|ва)|игра и тело/giu,
  ],
  [
    'behavioral',
    /в жизни|лестниц|тайм-аут|управление гневом|экспозиц|навык|учат |тренинг|домашн\S* задан|эксперимент|пробовать|попробовать|привычк|расписани|распорядок|шаг за шагом|маленьк\S* шаг|поведенч|на практике|упражня/giu,
  ],
  [
    'cognitive',
    /когнитивн|за и против|провер|оспарива|доказательств|шкал|мысл|убежден|карточк|объясн|различа|называ(?:ть|ют)|пересмотр|переоцен|список|подсч[её]т|дневник|связыва|просвещ/giu,
  ],
];

/**
 * Канал метода, о котором пункт: чей корень встретился раньше всех, а действие пункта стоит в первой фразе.
 * Ни один не подошёл — «На сессии», общая рубрика работы в кабинете.
 */
export function guessPlanRubric(text: string): PlanRubric {
  const lower = text.toLowerCase();
  let best: { rubric: PlanRubric; at: number } = {
    rubric: 'session',
    at: Infinity,
  };
  for (const [rubric, stems] of CHANNEL_STEMS) {
    stems.lastIndex = 0;
    const at = stems.exec(lower)?.index ?? Infinity;
    if (at < best.at) best = { rubric, at };
  }
  return best.rubric;
}
