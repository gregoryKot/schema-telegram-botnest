/** Что открыто по умолчанию сверх трекера и заданий: оба тумблера выше. */
export const THERAPIST_SEES_BY_DEFAULT =
  'дневники, карточки и списки схем и режимов, результаты теста схем';

/** Экран согласия по коду терапевта: что откроется сразу и где это закрыть. */
export function therapistJoinExplain(tr: Tr): string {
  const rest = `Трекер потребностей и задания терапевт видит всегда, а по умолчанию ещё ${THERAPIST_SEES_BY_DEFAULT}. Их можно закрыть в настройках, раздел «Мой терапевт», а терапевта — отключить в любой момент.`;
  return tr(
    `Код от терапевта — это согласие открыть ему доступ к твоим записям. ${rest}`,
    `Код от терапевта — это согласие открыть ему доступ к вашим записям. ${rest}`,
  );
}

export const JOIN_DONE_TITLE = 'Доступ открыт';

/**
 * Подсказка под заголовком «Мой терапевт». QA 2026-11 (М7): прежняя «остальное
 * — на усмотрение клиента» читалась как «закрыто, пока не откроешь», а ниже
 * было сказано, что дневники и тест открыты по умолчанию.
 */
export function therapistSectionHint(connected: boolean): string {
  const always =
    'Трекер и задания терапевт видит всегда, а дневники, карточки и тест — по умолчанию.';
  return connected
    ? `${always} Закрыть их можно тумблерами ниже.`
    : `${always} Закрыть их можно здесь же после подключения.`;
}

/**
 * Что изменилось после подключения — сразу, а не молча закрытым окном.
 * `inSettings` — текст стоит в самом разделе «Мой терапевт», над тумблерами:
 * «закрыть можно в настройках, раздел «Мой терапевт»» отправляло человека
 * туда, где он уже находится (QA 2026-11, М7).
 */
export function joinDoneText(
  name: string | null,
  tr: Tr,
  inSettings = false,
): string {
  const who = name ? `Терапевт ${name}` : 'Терапевт';
  const where = inSettings
    ? 'Закрыть их можно тумблерами ниже.'
    : 'Закрыть их можно в настройках, раздел «Мой терапевт».';
  const rest = `а по умолчанию ещё ${THERAPIST_SEES_BY_DEFAULT}. ${where}`;
  return tr(
    `${who} видит твой трекер потребностей и задания, ${rest}`,
    `${who} видит ваш трекер потребностей и задания, ${rest}`,
  );
}

