// Тексты связи клиент↔терапевт после инцидента 2026-10-26 — одни на оба
// фронтенда (правило №3): подсказка терапевту, куда клиенту вводить код;
// статус «Мой терапевт»; подтверждение после подключения; подтверждение
// отключения. Род нейтральный: «Анна Терапевт подключён» было мужским родом
// при любом имени терапевта.
type Tr = (ty: string, vy: string) => string;

/**
 * Терапевту рядом с кодом: ссылка открывает мини-приложение только в
 * Telegram, на сайте и в MAX код вводят руками. Путь сверен с экранами:
 * сайт — «Профиль» → «Настройки» → раздел «Мой терапевт»; мини-апп —
 * вкладка «Я» → шестерёнка «Настройки» → «Мой терапевт».
 */
export const INVITE_CODE_HINT =
  'По ссылке приложение откроется в Telegram. На сайте и в MAX код вводят вручную: Профиль → Настройки → «Мой терапевт» (в мини-приложении вместо «Профиля» — вкладка «Я»).';

/** Заголовок «Мой терапевт» при живой связи: имя, если оно есть в профиле. */
export function therapistConnectedTitle(name: string | null): string {
  return name ? `Терапевт: ${name}` : 'Подключение к терапевту активно';
}

export const JOIN_DONE_TITLE = 'Доступ открыт';

/** Что изменилось после подключения — сразу, а не молча закрытым окном. */
export function joinDoneText(name: string | null, tr: Tr): string {
  const who = name ? `Терапевт ${name}` : 'Терапевт';
  return tr(
    `${who} видит твой трекер потребностей и задания. Дневники, карточки схем и результаты опросников — только то, что откроешь в настройках, раздел «Мой терапевт».`,
    `${who} видит ваш трекер потребностей и задания. Дневники, карточки схем и результаты опросников — только то, что откроете в настройках, раздел «Мой терапевт».`,
  );
}

/** Строка экрана согласия: чей код (имя приходит с сервера до подключения). */
export function inviteFromLine(name: string): string {
  return `Приглашение от терапевта: ${name}`;
}

/** Код по ссылке не действует — сказать до согласия, а не после. */
export function inviteInvalidText(tr: Tr): string {
  return tr(
    'Эта ссылка больше не действует: её уже использовали, отозвали или прошла неделя. Попроси у терапевта новую.',
    'Эта ссылка больше не действует: её уже использовали, отозвали или прошла неделя. Попросите у терапевта новую.',
  );
}

