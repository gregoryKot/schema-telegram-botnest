// Тексты связи клиент↔терапевт после инцидента 2026-10-26 — одни на оба
// фронтенда (правило №3): подсказка терапевту, куда клиенту вводить код;
// статус «Мой терапевт»; подтверждение после подключения; подтверждение
// отключения. Род нейтральный: «Анна Терапевт подключён» было мужским родом
// при любом имени терапевта.
export type Tr = (ty: string, vy: string) => string;

/**
 * Терапевту рядом с кодом. С аудита 2026-11 (U3) ссылка ведёт на сайт
 * (`/today?startapp=therapy_…`): клиент входит любым способом, и сайт
 * подключает его тем же экраном согласия, что ссылка Telegram. Код вводят
 * в настройках, раздел «Мой терапевт» — одинаково на сайте, в Telegram и в
 * MAX (это один и тот же сайт); «вкладки «Я»» после единого фронтенда нет.
 */
export const INVITE_CODE_HINT =
  'Ссылка открывает приложение на сайте: клиент входит любым способом и подтверждает подключение. Без ссылки код вводят вручную в настройках, раздел «Мой терапевт».';

// Имя — только в формуле «роль: имя» или через «·»: имя склонять нечем, а
// «Задание для Ольга», «с Анна Терапевт» ломались на любом имени (QA 2026-11).

/** «Терапевт: имя» — статус «Мой терапевт», баннер ближайшей встречи. */
export function therapistNameLine(name: string): string {
  return `Терапевт: ${name}`;
}

/** Заголовок листа «новое задание»; у терапевта — с именем клиента. */
export function taskSheetTitle(clientName?: string | null): string {
  return clientName ? `Задание · ${clientName}` : 'Новое задание';
}

/** Заголовок «Мой терапевт» при живой связи: имя, если оно есть в профиле. */
export function therapistConnectedTitle(name: string | null): string {
  return name ? therapistNameLine(name) : 'Подключение к терапевту активно';
}

