// Тексты экрана-согласия на присоединение по ссылке (JoinConfirmSheet обоих
// фронтендов, правило №3). «Откуда и зачем» и ЧЕСТНЫЙ объём видимости: партнёр
// видит и неделю изменений, терапевт по умолчанию видит всё (therapistLinkCopy).
// Заголовок нейтрален (без ты/вы), объяснение разведено по форме обращения.
import { therapistJoinExplain, type Tr } from './therapistLinkCopy';

export function joinConfirmTitle(isPair: boolean): string {
  return isPair ? 'Присоединиться к паре?' : 'Открыть доступ терапевту?';
}

export function joinConfirmExplain(isPair: boolean, tr: Tr): string {
  return isPair
    ? tr(
        'Пара — это взаимная видимость с другим человеком. Партнёр увидит твой индекс дня (число от 0 до 10) и как он менялся последнюю неделю. Ты увидишь его. Дневники, заметки и оценки по потребностям остаются только у тебя.',
        'Пара — это взаимная видимость с другим человеком. Партнёр увидит ваш индекс дня (число от 0 до 10) и как он менялся последнюю неделю. Вы увидите его. Дневники, заметки и оценки по потребностям остаются только у вас.',
      )
    : therapistJoinExplain(tr);
}
