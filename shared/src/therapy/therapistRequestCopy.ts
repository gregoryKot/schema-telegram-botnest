// Строки заявки на роль психолога, общие для обеих форм: лист настроек сайта
// (`webapp/src/components/settingsSheet/BecomeTherapistSection.tsx`) и
// страница /account (`webapp/src/pages/account/TherapistRequestSection.tsx`).
// До 2026-11 формы обещали разное: «Решение появится здесь» и «Сообщим в
// Telegram, на почту» (аудит 2026-11, U12).
//
// Обещание повторяет доставку как она есть (`src/therapy/therapist-request.deliver.ts`):
// Telegram, если он привязан к аккаунту, иначе письмо на почту аккаунта; нет ни
// того, ни другого — владелец получает сигнал и пишет по контактам из заявки.
// Статус обе формы читают с сервера при открытии, поэтому «виден здесь».

type Tr = (ty: string, vy: string) => string;

/** Заявка на рассмотрении: куда придёт решение. Обращения в строке нет. */
export const THERAPIST_REQUEST_PENDING =
  'Заявка на рассмотрении. О решении сообщим в Telegram, если он подключён, ' +
  'иначе — на почту или по контактам из заявки. Статус тоже будет виден здесь.';

/** Заявка одобрена: что сделать, чтобы появился кабинет. */
export function therapistRequestApprovedText(tr: Tr): string {
  return tr(
    'Заявка одобрена. Перезайди в приложение, чтобы появился кабинет терапевта.',
    'Заявка одобрена. Перезайдите в приложение, чтобы появился кабинет терапевта.',
  );
}
