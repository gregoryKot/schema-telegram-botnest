/**
 * Переводит путь из базового пространства (x, y в чередовании) в пиксельные
 * координаты: x умножается на sx, y — на sy. Контур рисуется 1:1 в пикселях,
 * поэтому обводка одной толщины со всех сторон при любом соотношении сторон.
 */
export function scalePath(d: string, sx: number, sy: number): string {
  let i = 0;
  return d.replace(/-?\d+(\.\d+)?/g, (n) =>
    (parseFloat(n) * (i++ % 2 === 0 ? sx : sy)).toFixed(2),
  );
}
