              'По умолчанию открыты и дневники, карточки и списки схем и режимов, результаты теста схем. Что из этого закрыть, решаешь ты — в настройках, раздел «Мой терапевт».',
              'По умолчанию открыты и дневники, карточки и списки схем и режимов, результаты теста схем. Что из этого закрыть, решаете вы — в настройках, раздел «Мой терапевт».',
