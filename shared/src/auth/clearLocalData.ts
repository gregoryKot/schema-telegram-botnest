// Клинический контент (письма, безопасное место, черновики дневника, ответы
// YSQ, ярлыки схем) зеркалится в localStorage ради мгновенной отрисовки. При
// выходе — особенно на общем устройстве — его надо стереть, иначе следующий
// человек за этим браузером всё прочитает. Сервер остаётся источником правды,
// так что при следующем входе ничего не потеряется. Общий модуль (правило №3).
import { PENDING_LAUNCH_KEY } from '../host/startParam';

// Переживают очистку только безобидные ключи: тема ('app_theme'), решение по
// кукам-баннеру и отложенная ссылка запуска — она ждёт входа, а вход в другой
// аккаунт (ensureDataOwner) стирал бы её (#1024; живёт час, клиники в ней нет).
// Список здесь, а не в компоненте: «добавил ключ — забыл про выход» не молча.
const KEEP_KEYS = ['app_theme', 'cookie_consent', PENDING_LAUNCH_KEY];

export function clearLocalData(): void {
  try {
    const kept = KEEP_KEYS.map((k) => [k, localStorage.getItem(k)] as const);
    localStorage.clear();
    sessionStorage.clear();
    for (const [k, v] of kept) if (v !== null) localStorage.setItem(k, v);
  } catch {
    /* приватный режим/забитая квота — выход всё равно должен состояться */
  }
}
