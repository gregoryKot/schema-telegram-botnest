// «Этот контейнер уже входил» — одна отметка на оба фронтенда (правило №3).
//
// Зачем. Экран входа показывался одинаково новичку и человеку, у которого
// только что умерла сессия: «Войдите, чтобы продолжить». Для первого это
// правда, для второго — молчание о том, что произошло. Жалоба звучала как
// «приложение не сообщает, просто выкидывает» (разбор 2026-08-28).
//
// Отметка нужна ИМЕННО пер-контейнер: установленное приложение и вкладка
// браузера имеют своё хранилище, и «входил на сайте» ничего не говорит о том,
// входили ли с ярлыка. localStorage здесь ровно это и означает.
//
// Никаких данных: только факт. Личное в постоянном хранилище — под запретом
// отдельным пунктом CLAUDE.md.
// Отказ хранилища (приватный режим, забитая квота) — забота одного примитива
// на весь проект: shared/src/utils/safeLocalStorage.
import { readLocal, removeLocal, writeLocal } from '../utils/safeLocalStorage';

const KEY = 'auth_seen';

export function markAuthSeen(): void {
  writeLocal(KEY, '1');
}

/** true — в этом контейнере вход уже удавался, значит сессия истекла. */
export function hasAuthSeen(): boolean {
  return readLocal(KEY) === '1';
}

/** Выход — это осознанное действие, а не авария: отметку снимаем. */
export function clearAuthSeen(): void {
  removeLocal(KEY);
}
