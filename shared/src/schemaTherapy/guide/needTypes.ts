import type { NeedId } from '../../needs/types';

/** Лист потребности во вкладке «Потребности»: текст для терапевта, не клиентское описание. */
export interface NeedGuide {
  /** id потребности из shared/src/needs. */
  id: NeedId;
  /** Подпись в списке вкладки; слово из названия потребности не повторяет. */
  subtitle: string;
  /** Что это за потребность, 1–2 фразы — под заголовком листа. */
  essence: string;
  /** Как выглядит её фрустрация в детстве. */
  frustration: string;
  /** Какие схемы домена из неё растут: каждая схема домена названа. */
  schemas: string;
  /** Что с этим делает ограниченное родительство. */
  care: string;
  sources: string;
}
