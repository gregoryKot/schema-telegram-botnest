import { withYoung } from '../youngAdd';
import { EARLY_PHASES as EARLY_PHASES_BASE } from './early';
import type { PhaseGuideBuilder } from './types';

/** Досбор по Янгу (гл. 2) к фазе «Оценка и психообразование»: другие источники гипотез, книга самопомощи. Вынесено, чтобы early.ts не рос. */
export const EARLY_PHASES: PhaseGuideBuilder[] = EARLY_PHASES_BASE.map(
  (build): PhaseGuideBuilder =>
    (tr) => {
      const phase = build(tr);
      if (phase.id !== 'assessment') return phase;
      return withYoung(phase, {
        more: [
          'Ещё источники гипотез о схемах [Янг, гл. 2]: сильные реакции на текущие события, их разбирают на сессии, и поведение в группе — как клиент реагирует на участников и темы.',
          'Сны, особенно повторяющиеся и с сильным чувством [Янг, гл. 2]: клиент их записывает, и сон становится входом в работу с образами. Книга или фильм под гипотезу терапевта: реакция клиента подтверждает её или опровергает.',
          'Книга самопомощи работает потому, что клиенты узнают себя в героях примеров и вовлекаются эмоционально [Янг, гл. 2]. Сначала читают пять коротких вводных глав, затем одну-две главы о главных схемах.',
          'В главах о ловушках есть сигналы опасности при выборе партнёра: признаки отношений, которые подкрепят схему [Янг, гл. 2].',
          'Самонаблюдение показывает клиенту, насколько автоматически и повсеместно включаются схемы [Янг, гл. 2]. Саморазрушительное поведение замечается раньше, чем получается его изменить, и это нормальный шаг.',
        ],
      });
    },
);
