import type { ModeGuide, ModeGuideBuilder } from '../types';
import { buildAvoidanceGuides as buildAvoidanceBase } from './avoidance';
import { buildSurrenderGuides as buildSurrenderBase } from './surrender';

/** «Подробнее» к режимам из клинических примеров Арнтц и Якоб, гл. 1.3: как копинг выглядит в жизни. */
const MODE_ARNTZ_INTRO: Record<string, string[]> = {
  compliant_surrenderer: [
    'Как капитуляция выглядит в жизни [Арнтц, 1.3.1]: клиент отвечает на звонки бывшего партнёра, который с ним был груб, возвращается и вступает в близость без желания. Встречи дают хотя бы миг человеческого тепла («всё равно никому не нужно»), а рассказать другому, чего ждёшь от него, представить невозможно: кажется, что это никого не интересует. Так же люди с тяжёлым сексуальным насилием в детстве смиряются с насилием в близких отношениях взрослой жизни.',
  ],
  detached_self_soother: [
    'Пример избегания [Арнтц, 1.3.2]: после сексуального насилия в детстве любой разговор с мужчиной вызывает панику и чувство загнанности, хочется бежать и прятаться. Помогает алкоголь в больших количествах, но полной безопасности нет и под ним: он лишь даёт эйфорию и притупляет ощущение угрозы. В таком состоянии случаются связи с малознакомыми без всяких чувств; трезвым ни одного контакта не было. Стыд за выпивку и связи острый, но без алкоголя расслабиться нельзя: даже решив не пить на вечеринке, человек напивается или отказывается от приглашения в последнюю минуту. Избегание боли даёт новый стыд, а он — новый повод избегать.',
  ],
};

/** Дополняет режимы «Подробнее» из гл. 1.3 книги. */
const withModeIntro =
  (build: ModeGuideBuilder): ModeGuideBuilder =>
  (tr) =>
    build(tr).map((m: ModeGuide) => {
      const extra = MODE_ARNTZ_INTRO[m.modeId];
      return extra ? { ...m, more: [...(m.more ?? []), ...extra] } : m;
    });

export const buildSurrenderGuides = withModeIntro(buildSurrenderBase);
export const buildAvoidanceGuides = withModeIntro(buildAvoidanceBase);
