/** Вставляет абзацы сразу после абзаца, начинающегося с `start`; не нашёл — в конец (тест следит, что находит). */
export function insertAfter(
  list: string[],
  start: string,
  items: string[],
): string[] {
  const i = list.findIndex((t) => t.startsWith(start));
  return i < 0
    ? [...list, ...items]
    : [...list.slice(0, i + 1), ...items, ...list.slice(i + 1)];
}

