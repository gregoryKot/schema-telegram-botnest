import { describe, expect, it } from 'vitest';
import { joinSentences, splitSentences } from './sentences';

describe('splitSentences', () => {
  it('делит по точке перед заглавной буквой', () => {
    expect(
      splitSentences('Остановить сразу. Потом назвать чувство! А дальше?'),
    ).toEqual(['Остановить сразу.', 'Потом назвать чувство!', 'А дальше?']);
  });

  it('точки внутри ссылки на источник предложение не рвут', () => {
    const text =
      'Остановить сразу и от первого лица [Арнтц, 5.1.1]. Сначала граница, потом конфронтация [Хис, гл. 12].';
    expect(splitSentences(text)).toEqual([
      'Остановить сразу и от первого лица [Арнтц, 5.1.1].',
      'Сначала граница, потом конфронтация [Хис, гл. 12].',
    ]);
  });

  it('ссылка за точкой остаётся со своим предложением', () => {
    expect(
      splitSentences(
        'Дать слово ребёнку. [Хис, гл. 11] Потом вернуться к взрослому.',
      ),
    ).toEqual([
      'Дать слово ребёнку. [Хис, гл. 11]',
      'Потом вернуться к взрослому.',
    ]);
  });

  it('сокращение со строчной после точки — не конец предложения', () => {
    expect(
      splitSentences('Назвать режим, т. е. дать ему имя. Потом спросить.'),
    ).toEqual(['Назвать режим, т. е. дать ему имя.', 'Потом спросить.']);
  });

  it('кавычка закрывается вместе с предложением; пустой текст — без частей', () => {
    expect(splitSentences('Сказать: «Я рядом.» Подождать ответ')).toEqual([
      'Сказать: «Я рядом.»',
      'Подождать ответ',
    ]);
    expect(splitSentences('  ')).toEqual([]);
  });
});

describe('joinSentences', () => {
  it('склеивает части пробелом и возвращает исходный текст', () => {
    const text = 'Остановить сразу [Арнтц, 5.1.1]. Потом граница.';
    expect(joinSentences(splitSentences(text))).toBe(text);
  });

  it('части без точки в середине получают точку, последняя — нет', () => {
    expect(
      joinSentences(['Дневник режимов', ' Записывать раз в день ', '']),
    ).toBe('Дневник режимов. Записывать раз в день');
  });
});
