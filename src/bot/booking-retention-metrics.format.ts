import { plural } from './plural';

// Блок «Данные записей» для /stats (правило №8: механизм без строки в отчёте
// невидим). Показывает, как работает ночное стирание имени, контакта и текста
// запроса у старых броней (booking-retention.service.ts, находка L3 аудита
// 2026-07-20). Чистый форматтер, покрыт тестом, включая пустую БД.
//
// Зачем блок вообще есть: крон ничего не шлёт наружу, а при сбое пишет одну
// строку в лог. Если он тихо встанет, имена и контакты начнут копиться дольше
// обещанного срока, и узнать об этом будет не из чего. Поэтому отчёт отвечает
// на три вопроса: стирается ли вообще, сколько записей ждут и не опаздывает ли
// ночной прогон.
//
// Язык простой: «стёрто у N записей», а не «anonymized rows».

export interface BookingRetentionMetrics {
  /** Через сколько месяцев после встречи данные стираются. */
  monthsKept: number;
  /** У скольких записей имя и контакт уже стёрты. */
  anonymized: number;
  /** Сколько записей ещё ждут своего срока. */
  waiting: number;
  /**
   * Через сколько дней срок выйдет у самой старой из ждущих. 0 — сегодня,
   * отрицательное — срок уже вышел, а ночной прогон его не забрал.
   * null — ждущих записей нет.
   */
  daysToNext: number | null;
}

function nextTermLine(days: number): string {
  if (days < 0) {
    const late = -days;
    return (
      `⚠️ Ночное стирание опаздывает: у самой старой записи срок вышел ` +
      `${late} ${plural(late, 'день', 'дня', 'дней')} назад.`
    );
  }
  if (days === 0) return 'У самой старой записи срок подошёл — сотрётся ночью.';
  if (days === 1) return 'Ближайший срок — завтра.';
  return `Ближайший срок — через ${days} ${plural(days, 'день', 'дня', 'дней')}.`;
}

/** Текстовый блок для /stats. Чистая функция. */
export function formatBookingRetention(m: BookingRetentionMetrics): string {
  const lines = [
    '🗂 <b>Данные записей</b>',
    `Имя, контакт и текст запроса стираются через ${m.monthsKept} ` +
      `${plural(m.monthsKept, 'месяц', 'месяца', 'месяцев')} после встречи. ` +
      'Сама запись остаётся.',
  ];
  if (m.anonymized === 0 && m.waiting === 0) {
    lines.push('Записей пока нет, стирать нечего.');
    return lines.join('\n');
  }
  lines.push(
    m.anonymized > 0
      ? `Уже стёрто у ${m.anonymized} ${plural(m.anonymized, 'записи', 'записей', 'записей')}.`
      : 'Пока не стёрто ни у одной: срок ещё ни у кого не вышел.',
  );
  if (m.waiting > 0 && m.daysToNext !== null) {
    lines.push(
      `Своего срока ждут ${m.waiting} ${plural(m.waiting, 'запись', 'записи', 'записей')}.`,
      nextTermLine(m.daysToNext),
    );
  } else {
    lines.push('Ждущих срока записей нет.');
  }
  return lines.join('\n');
}
