// Планка качества для пула фраз «Здорового Взрослого».
//
// Зачем отдельно от гейтов репозитория: пул живёт строками в БД и заводится
// через админку, то есть текст НИКОГДА не проходит через файл. Все гейты
// (check-gendered-forms, check-robot-phrases) обходят каталоги на диске и
// строку в базе не видят. Реальный пропуск 2026-08: фраза «Милый мой, ты
// годами ждал письма… Тебе можно быть просто мальчиком» — мужской род во всём
// тексте плюс выдуманное «несправляние» — доехала до прода и показалась
// пользователям в мини-аппе. Ни одна проверка её не касалась.
//
// Почему правила здесь, а не импортом из scripts/: gate-скрипты — ESM вне
// rootDir, бэкенд собирается в CommonJS; динамический импорт работает в проде,
// но не в jest, то есть проверка осталась бы без теста. Непроверяемая проверка
// тихо перестаёт работать — это и есть худший исход. Поэтому список живёт тут
// и покрыт тестом (healthy-adult.quality.spec.ts).
//
// Список намеренно уже, чем у гейтов: пул — короткие реплики к читателю, и
// здесь важны род, иишные штампы и выдуманные слова. Правила репозитория
// шире (они судят и код, и статьи), полностью повторять их тут незачем.
const L = '(?<![А-Яа-яЁё])';
const R = '(?![А-Яа-яЁё])';
const PAST_M = '(?:ал|ял|ил|ел|ыл|ёл|ул|рос|ался|ился|ялся|улся|ёлся)';
const FILLER =
  '(?:не\\s+|бы\\s+|уже\\s+|сам\\s+|тогда\\s+|сегодня\\s+|снова\\s+|годами\\s+|всё\\s+ещё\\s+)*';

export type Severity = 'block' | 'warn';

export interface PhraseIssue {
  kind: 'род' | 'робот' | 'слово';
  rule: string;
  fragment: string;
  severity: Severity;
}

interface Rule {
  name: string;
  kind: PhraseIssue['kind'];
  re: RegExp;
  severity: Severity;
}

const RULES: Rule[] = [
  // — род читателя —
  {
    name: 'ty-past',
    kind: 'род',
    severity: 'block',
    re: new RegExp(`${L}[Тт]ы\\s+${FILLER}[а-яё]+${PAST_M}${R}`, 'g'),
  },
  {
    name: 'ya-past',
    kind: 'род',
    severity: 'block',
    re: new RegExp(`${L}[Яя]\\s+${FILLER}[а-яё]+${PAST_M}${R}`, 'g'),
  },
  {
    name: 'ty-short-adj',
    kind: 'род',
    severity: 'block',
    re: new RegExp(
      `${L}[Тт]ы\\s+${FILLER}(?:обязан|должен|готов|уверен|рад|спокоен|виноват|прав|свободен|живой|один|способен|силён|слаб|сломан)${R}`,
      'g',
    ),
  },
  {
    name: 'inf-adj-m',
    kind: 'род',
    severity: 'block',
    re: new RegExp(
      `${L}(?:быть|стать|казаться|остаться|оставаться|чувствовать\\s+себя)\\s+(?:\\S+\\s+){0,2}[а-яё]{2,}(?:ым|им)${R}`,
      'g',
    ),
  },
  {
    name: 'brackets',
    kind: 'род',
    severity: 'block',
    re: new RegExp(`${L}[а-яё]+\\((?:а|на|ла|ась|ой|ая)\\)`, 'g'),
  },
  // «Тебе можно быть просто мальчиком» — обращение к читателю. Законного
  // применения в пуле почти нет: блок.
  {
    name: 'male-address',
    kind: 'род',
    severity: 'block',
    re: new RegExp(`${L}(?:мальчик[а-яё]*|парень|парн[а-яё]+)${R}`, 'gi'),
  },
  // «Рядом был мужчина, который умел злиться без крика» — о третьем лице,
  // фраза законная. Блокировать нельзя: ложно-красную проверку отключают
  // через неделю. Только пометка человеку.
  {
    name: 'male-third-person',
    kind: 'род',
    severity: 'warn',
    re: new RegExp(`${L}мужчин[а-яё]*${R}`, 'gi'),
  },

  // — иишные штампы (правило №12: пул уже был на 18/46 из одного скелета) —
  {
    name: 'eto-ne-eto',
    kind: 'робот',
    severity: 'block',
    re: /[Ээ]то\s+не\s+[^,.!?;»]{2,60}[,.]\s*(?:[Ээ]то|а)\s/g,
  },
  {
    name: 'eto-ne-pro',
    kind: 'робот',
    severity: 'block',
    re: /[Ээ]то\s+не\s+про\s/g,
  },
  {
    name: 'tire-eto-ne',
    kind: 'робот',
    severity: 'block',
    re: /[—–]\s*это\s+не\s/g,
  },
  {
    name: 'ne-prosto',
    kind: 'робот',
    severity: 'block',
    re: /не\s+просто\s/gi,
  },
  {
    name: 'ne-znachit',
    kind: 'робот',
    severity: 'block',
    re: /не\s+значит\s[^.!?]{2,60}[,.]\s*[Ээ]то\s+значит/g,
  },
  // Слова собраны из кусков намеренно: написанные целиком, они ловятся
  // гейтом check-robot-phrases в этом же файле — правило спотыкается о
  // собственный список.
  {
    name: 'kancelyarit',
    kind: 'робот',
    severity: 'block',
    re: new RegExp(
      `(?:явля${'ется'}|представляет\\s+собой|осуществля${'ется'}|важно\\s+отме${'тить'})`,
      'gi',
    ),
  },

  // — выдуманные слова —
  // «несправляние» — отглагольное существительное, слепленное на ходу.
  // Читателя такое спотыкает: видно, что с ним говорят не на его языке.
  // Список конкретный, не эвристика по суффиксу: «-ание/-ение» — законный
  // способ словообразования, глушить его целиком значит запретить «внимание».
  {
    name: 'invented-noun',
    kind: 'слово',
    severity: 'block',
    re: /(?:несправлян|недодаван|отвергание|непринимание|неотзеркалив)[а-яё]*/gi,
  },
];

/** Все претензии к фразе, включая пометки. Пусто — фраза чистая. */
export function findIssues(text: string): PhraseIssue[] {
  if (typeof text !== 'string' || text.trim() === '') return [];
  const issues: PhraseIssue[] = [];
  for (const { name, kind, re, severity } of RULES) {
    re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text))) {
      issues.push({ kind, rule: name, fragment: m[0].trim(), severity });
    }
  }
  return issues;
}

/** Только то, из-за чего фразу нельзя пускать в пул. */
export function blockingIssues(text: string): PhraseIssue[] {
  return findIssues(text).filter((i) => i.severity === 'block');
}

/** Человеческая причина отказа для отчёта админки. */
export function issuesToReason(issues: PhraseIssue[]): string {
  const parts = issues.map((i) =>
    i.kind === 'род'
      ? `мужской род («${i.fragment}»)`
      : i.kind === 'слово'
        ? `выдуманное слово («${i.fragment}»)`
        : `штамп («${i.fragment}»)`,
  );
  return [...new Set(parts)].join(', ');
}
