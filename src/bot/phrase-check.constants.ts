// Приметы, по которым разбирается фраза внутреннего голоса — все девять строк
// таблицы «разрушительная самокритика ↔ помогающая самокоррекция»: цель фразы,
// позиция «ты не ОК», направленность на личность, ярлыки вместо фактов,
// движущая сила, отношение к сделанному и к ошибкам, чёрно-белость и
// зависимость ценности человека от результата.
//
// Здесь — только id: тексты живут во фронтенде
// (schema-miniapp/src/components/phraseCheck/criteria.ts), бэкенду они не
// нужны, а вот валидация присланных id — нужна (данные от клиента не
// принимаются на веру).
//
// Список продублирован во фронтенде, потому что бэкенд не может импортировать
// shared (tsconfig rootDir=src) — как quiz-logic.ts ↔ quizEngine.ts. Паритет
// закреплён одинаковыми списками в phrase-check.service.spec.ts и
// criteria.test.ts: правка одной стороны роняет тест другой.
export const PHRASE_MARK_IDS = [
  // цель: ткнуть в промах и обесценить сделанное
  'goal',
  // позиция «ты не ОК»
  'notok',
  // направлена на личность, а не на поступок
  'person',
  // оценивает и вешает ярлыки вместо фактов и последствий
  'label',
  // движущая сила — страх и чужой взгляд, а не желание
  'fear',
  // никогда не довольна, не замечает улучшений
  'never',
  // ошибка = провал, которого нельзя допускать
  'mistake',
  // крайности, чёрно-белое мышление
  'absolute',
  // ценность человека поставлена в зависимость от результата
  'worth',
] as const;

export type PhraseMarkId = (typeof PHRASE_MARK_IDS)[number];

export function isPhraseMarkId(value: string): value is PhraseMarkId {
  return (PHRASE_MARK_IDS as readonly string[]).includes(value);
}
