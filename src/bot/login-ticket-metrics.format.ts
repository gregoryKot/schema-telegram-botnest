// Блок «Вход по коду» для /stats (правило №8: метрика, которой нет в отчёте,
// — невидима). Чистый форматтер, покрыт тестом, включая пустую БД.
//
// Зачем блок. Механизм билета переписал вход целиком, а судить о нём было не
// по чему: сломанный вход не крашится, он просто оставляет человека на экране
// входа. Молчаливую поломку видно только по числам.
//
// Чего в блоке НЕТ и почему. Доля успеха считается от ПОДТВЕРЖДЁННЫХ, а не от
// выписанных кодов: код выписывается автоматически при открытии экрана и
// повторно по кнопке «попробовать снова», то есть «просили код» — это показы,
// а не намерения, и в аварию их число растёт само. Разбивки по способу входа
// (Telegram/Google/VK/почта) тоже нет: билет выписывается один на весь экран,
// и такая цифра была бы выдуманной.
//
// Язык простой: «дошли до конца N из M», а не «conversion rate».
import { plural } from './plural';

export interface LoginTicketMetrics {
  /** Экран входа просил код (показы, не намерения). */
  issued: number;
  /** Открыли ссылку в боте — только телеграм-путь, поэтому отдельной строкой. */
  botOpened: number;
  /** Вход подтверждён — все способы. */
  confirmed: number;
  /** Приложение забрало сессию. Единственное «человек внутри». */
  taken: number;
  /** Открыли или нажали, когда код уже мёртв. */
  tooLate: number;
  /** Сказали «это не я». */
  denied: number;
}

/** Текстовый блок для /stats. Чистая функция. */
export function formatLoginTicket(m: LoginTicketMetrics): string {
  const lines = ['🎟 <b>Вход по коду</b> (за неделю)'];

  if (m.issued === 0 && m.confirmed === 0) {
    lines.push(
      'За неделю кодом входа не пользовались — сравнивать пока не с чем.',
    );
    return lines.join('\n');
  }

  if (m.confirmed === 0) {
    lines.push(
      `Код просили ${m.issued} ${plural(m.issued, 'раз', 'раза', 'раз')}, ` +
        'но ни один не подтвердили. Похоже, ссылка подтверждения до людей ' +
        'не доходит.',
    );
    return lines.join('\n');
  }

  lines.push(
    `Экран входа просил код: ${m.issued} ` +
      `${plural(m.issued, 'раз', 'раза', 'раз')} (это показы, не люди)`,
  );
  lines.push(`Подтвердили вход: ${m.confirmed}`);
  lines.push(`Приложение впустило: ${m.taken} из ${m.confirmed}`);

  if (m.confirmed > m.taken) {
    lines.push(
      `Подтвердили, но внутрь так и не попали: ${m.confirmed - m.taken} — ` +
        'вход прошёл, а приложение осталось на экране входа.',
    );
  }
  if (m.botOpened > 0) {
    lines.push(`Открывали ссылку в боте: ${m.botOpened}`);
  }
  if (m.tooLate > 0) {
    lines.push(`Не успели вовремя: ${m.tooLate}`);
  }
  if (m.denied > 0) {
    lines.push(`Сказали «это не я»: ${m.denied}`);
  }
  return lines.join('\n');
}
