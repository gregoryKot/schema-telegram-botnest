// Пул фраз живёт в БД, а не в файлах, поэтому гейты репозитория его не видят
// (реальный пропуск 2026-08: фраза «Милый мой, ты годами ждал письма… Тебе
// можно быть просто мальчиком» с мужским родом и выдуманным «несправлянием»
// доехала до прода). Проверка стоит на входе — здесь её и пиним.
//
// Тест пинит обе стороны: что блокируется (род, «мальчиком», выдуманные слова,
// иишные штампы) и что проходит (живая фраза, «мужчина» о третьем лице).
// Вторая половина не менее важна: проверка, которая режет законный текст,
// доживает до первой жалобы и отключается.
import { blockingIssues, issuesToReason } from './healthy-adult.quality';

describe('healthy-adult.quality — планка для пула фраз', () => {
  it('пропускает живую фразу без рода и штампов', () => {
    expect(
      blockingIssues(
        'Сегодня можно закрыть ноутбук на час раньше. Мир подождёт.',
      ),
    ).toEqual([]);
  });

  it('ловит мужской род, обращённый к читателю', () => {
    const issues = blockingIssues('Ты был хорошим ребёнком, и это правда.');
    expect(issues.length).toBeGreaterThan(0);
    expect(issues.some((i) => i.kind === 'род')).toBe(true);
  });

  it('ловит обращение «мальчиком» — с него начался свип', () => {
    const issues = blockingIssues('Тебе можно быть просто мальчиком.');
    expect(issues.map((i) => i.rule)).toContain('male-address');
  });

  it('ловит выдуманное слово «несправляние»', () => {
    const issues = blockingIssues('Их несправляние — не твоя вина.');
    expect(issues.map((i) => i.rule)).toContain('invented-noun');
  });

  it('ловит иишный штамп «это не X, это Y»', () => {
    const issues = blockingIssues(
      'Это не слабость. Это способ, которым психика себя защитила.',
    );
    expect(issues.some((i) => i.kind === 'робот')).toBe(true);
  });

  it('не блокирует «мужчину» о третьем лице — это пометка, не запрет', () => {
    expect(
      blockingIssues('Рядом был мужчина, который умел злиться без крика.'),
    ).toEqual([]);
  });

  it('причина отказа написана по-человечески', () => {
    expect(
      issuesToReason([
        {
          kind: 'род',
          rule: 'male-address',
          fragment: 'мальчиком',
          severity: 'block',
        },
      ]),
    ).toBe('мужской род («мальчиком»)');
  });
});
