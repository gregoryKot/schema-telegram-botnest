// Блок «Заявки с формы знакомства» для /stats (правило №8). Раньше заявка жила
// только в DM и письме: мертвы оба канала — следа нет, и узнать об этом было
// не из чего. Теперь заявка пишется в базу, а отчёт показывает, сколько их
// пришло и сколько не дошло до владельца. Чистый форматтер, покрыт тестом,
// включая пустое состояние. Язык простой: «не дошли ни в бот, ни на почту», без «delivery». Безличный: отчёт админский, без «вы» (гейт second-person).

export interface IntroLeadMetrics {
  /** Заявок за последние 7 дней. */
  week: number;
  /** Из них не дошедших ни в Telegram, ни на почту. */
  weekLost: number;
  /** Не дошедших старше недели (повтор доставки их уже не берёт). */
  olderLost: number;
}

export function formatIntroLeads(m: IntroLeadMetrics): string {
  const lines = ['📩 <b>Заявки с формы знакомства</b>'];
  if (m.week === 0) {
    lines.push('За неделю заявок не было.');
  } else if (m.weekLost === 0) {
    lines.push(`За неделю заявок: ${m.week}, все дошли.`);
  } else {
    lines.push(
      `⚠️ За неделю заявок: ${m.week}, не дошли ни в бот, ни на почту: ${m.weekLost}. ` +
        'Нужно проверить бота и почту: система досылает сама, до 5 попыток.',
    );
  }
  if (m.olderLost > 0) {
    lines.push(`⚠️ Недоставленных заявок старше недели: ${m.olderLost}.`);
  }
  return lines.join('\n');
}
