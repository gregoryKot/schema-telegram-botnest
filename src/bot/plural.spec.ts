// Русское склонение. Одна копия на все отчёты — раньше их было две.
import { plural } from './plural';

const raz = (n: number) => plural(n, 'раз', 'раза', 'раз');
const chel = (n: number) => plural(n, 'человек', 'человека', 'человек');

describe('plural', () => {
  it.each([
    [1, 'раз'],
    [2, 'раза'],
    [4, 'раза'],
    [5, 'раз'],
    [21, 'раз'],
    [22, 'раза'],
    [25, 'раз'],
    [101, 'раз'],
  ])('%i → %s', (n, want) => {
    expect(raz(n)).toBe(want);
  });

  // Одиннадцать–четырнадцать — та самая ловушка, из-за которой «11 раза».
  it.each([11, 12, 13, 14, 111, 112])('%i — множественное, не «раза»', (n) => {
    expect(raz(n)).toBe('раз');
  });

  it('ноль склоняется как множественное', () => {
    expect(chel(0)).toBe('человек');
  });

  it('другие слова склоняются тем же правилом', () => {
    expect(chel(1)).toBe('человек');
    expect(chel(3)).toBe('человека');
    expect(chel(7)).toBe('человек');
  });
});
