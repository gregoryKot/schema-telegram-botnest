/**
 * Аварийный потолок карты ключей: распределённый перебор с тысяч IP не должен
 * съесть память. Вытесняем САМЫЕ СТАРЫЕ записи — Map хранит порядок вставки,
 * а вызывающий при открытии окна переставляет ключ в конец (`delete` перед
 * `set`). Не `clear()`: он обнулял троттл, и следующий же повтор недавнего
 * ключа проходил — шквал алертов пролетал ровно тогда, когда ключей много
 * (находка 2026-10, docs/open/backend.md).
 */
export function evictOldest<V>(
  map: Map<string, V>,
  maxKeys: number,
  keep: string,
) {
  for (const k of map.keys()) {
    if (map.size <= maxKeys) return;
    if (k !== keep) map.delete(k);
  }
}
