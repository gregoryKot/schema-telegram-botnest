/**
 * FNV-1a — быстрый строковый хэш для «случайного, но стабильного» выбора.
 *
 * Криптостойкость тут не нужна, нужна равномерная размазанность и
 * повторяемость: минута публикации канала и внешний вид пина Pinterest
 * вычисляются из строки, а не из `Math.random()`. Иначе рестарт процесса или
 * повторная отправка того же текста дали бы другой результат — а значит,
 * дубль с другим оформлением и невоспроизводимые тесты.
 */
export function fnv1a(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Финальное перемешивание (fmix32 из MurmurHash3): у FNV-1a слабо разбросаны
 * младшие биты, а `% size` берёт именно их. Без него похожие строки — «фраза
 * 1», «фраза 2» — сваливались в один вариант оформления, и пины повторялись.
 */
function avalanche(h: number): number {
  h ^= h >>> 16;
  h = Math.imul(h, 0x85ebca6b);
  h ^= h >>> 13;
  h = Math.imul(h, 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

/** Индекс в массиве длиной `size`, стабильный для пары «строка + грань». */
export function pickIndex(seed: string, facet: string, size: number): number {
  // Берём старшие биты (умножение на size и сдвиг), а не остаток от деления.
  return Math.floor((avalanche(fnv1a(`${seed}:${facet}`)) / 2 ** 32) * size);
}
