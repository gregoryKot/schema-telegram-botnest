// Настоящий календарный день для DTO (QA 2026-10-26: `2026-02-31`,
// `2026-13-45` и `0000-00-00` проходили регэксп формы).
import { isCalendarDay } from './calendar-day';

describe('isCalendarDay', () => {
  it('настоящие дни, включая 29 февраля високосного года', () => {
    for (const ok of ['2026-10-26', '2028-02-29', '2026-12-31', '2026-01-01'])
      expect(isCalendarDay(ok)).toBe(true);
  });

  it('несуществующие и нулевые даты — нет', () => {
    for (const bad of [
      '2026-02-31',
      '2027-02-29',
      '2026-13-45',
      '2026-00-10',
      '2026-04-31',
      '0000-00-00',
      '0099-01-01',
    ])
      expect(isCalendarDay(bad)).toBe(false);
  });

  it('не та форма и не строка — нет', () => {
    for (const bad of [
      '2026-7-1',
      '26-10-2026',
      '2026-10-26T00:00',
      '',
      null,
      20261026,
    ])
      expect(isCalendarDay(bad)).toBe(false);
  });
});
