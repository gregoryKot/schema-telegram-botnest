// Деньги пришли, а отметка оплаты упала: владельцу — что не подтвердилось
// (бронь, подписка, донат с номером) и тип ошибки. Текст ошибки — только в
// логе приложения: в нём бывают аргументы запроса и ответ площадки (РКН, #1135).
import { errorType } from '../logger/alert-text';

export function paidButFailedAlert(what: string, e: unknown): string {
  return (
    `🚨 <b>Оплата прошла, но ${what}</b>\n` +
    `Тип ошибки: ${errorType([e])}, полный текст — в логе приложения. ` +
    'Нужна ручная проверка в админке.'
  );
}
