// Потолок размера тела HTTP-запроса — одно место на весь проект
// (правило «одна механика — один компонент»).
//
// Аудит 2026-07-20, L2. Подозрение аудита — «строки `json({limit:'256kb'})`
// в main.ts мёртвые, потому что NestFactory.create уже зарегистрировал свой
// парсер на 100 КБ» — ЗАМЕРОМ НЕ ПОДТВЕРДИЛОСЬ (test/body-limit.e2e-spec.ts):
// реальный потолок 262144 байта. Nest регистрирует свои парсеры не в
// `create()`, а в `init()` (его дёргает `listen()`) — то есть ПОСЛЕ наших
// `app.use(...)`; к тому же `registerParserMiddleware` пропускает парсер,
// если в стеке уже есть слой с таким же именем функции (`jsonParser` /
// `urlencodedParser`, см. node_modules/@nestjs/platform-express/adapters/
// express-adapter.js: `.filter(parser => !this.isMiddlewareApplied(parser))`).
//
// Работало это по совпадению двух деталей чужой реализации: порядка
// `use` / `listen` и совпадения ИМЁН функций-парсеров. Перестановка строк в
// bootstrap или переименование слоя у Nest молча уронили бы потолок до 100 КБ
// — без ошибки, без теста, до первой жалобы на 413. Поэтому main.ts теперь
// отключает штатный парсер явно (`bodyParser: false`) и ставит свой, а
// значение живёт здесь и пинится e2e-тестом.
//
// Откуда 256 КБ — посчитано по самым длинным законным телам, а не на глаз
// (прежний комментарий в main.ts называл максимумом прогресс YSQ: на деле
// это 254-256 байт, меньше всех прочих на три порядка):
//   • PATCH /api/site-content/admin/hero-photo — data-URI фотографии,
//     MAX_PHOTO_BYTES = 225 280 символов base64 + 14 байт обёртки JSON =
//     225 294 байта. Самое длинное тело по проекту; фронт при этом жмёт
//     фотографию до 200 КБ (webapp/src/pages/admin/PhotoSection.tsx);
//   • PATCH /api/therapy/mode-maps/map/:mapId — карта режимов целиком на
//     каждое автосохранение. Потолок DTO (200 узлов + 500 связей, без
//     заметок) даёт 232 871 байт; обычная карта на 30 узлов — около 52 КБ;
//   • POST/PATCH /api/articles/admin — content до 12,5 КБ (самая длинная
//     статья в ARTICLE_SEED) + heroImage до 160 КБ → около 177 КБ;
//   • дневники после срезки в контроллере — до ~38 КБ кириллицей,
//     концептуализация терапевта — до ~70 КБ; письма, заметки схем и
//     режимов, прогресс YSQ — заметно меньше.
// 256 КБ накрывает весь список: запас над фотографией ~36 КБ, над предельной
// картой режимов ~29 КБ. Поднимать потолок без пересчёта этого списка не
// надо — он считается от конкретного тела, а не «на всякий случай».
//
// Известный край (сознательно НЕ закрыт здесь): карта режимов, набитая до
// потолка DTO И с заметками во всех узлах, даёт ~414 КБ и упрётся в лимит.
// Лечится это не поднятием общего потолка (тогда он перестанет защищать
// остальные 60 ручек), а ограничением длины заметок в самой DTO —
// отдельная задача, строка в docs/README.md → «Что осталось открытым».
export const BODY_LIMIT = '256kb';

/** То же число в байтах — для сверок в тестах (`256kb` = 256 × 1024). */
export const BODY_LIMIT_BYTES = 256 * 1024;
