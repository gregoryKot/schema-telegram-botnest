// Кэширование статики: заголовок Cache-Control по типу файла.
//
// Измерено 2026-08-22 (Playwright, 3G RTT 400мс, прод-конфигурация): повторный
// запуск мини-аппа с ТЁПЛЫМ кэшем всё равно тратил 857мс до первой строчки JS —
// сначала круг за HTML, потом круг за ревалидацией бандла. Причина: вся статика
// отдавалась с `max-age=0`, то есть браузер спрашивал разрешение на каждый файл
// при каждом запуске.
//
// Разделяем по природе файла, а не «одним заголовком на всё»:
//   • имя с контент-хешем (сборка webapp: index-CTgJf44i.js) — файл иммутабелен
//     по построению: меняется содержимое → меняется имя. Такой можно кэшировать
//     на год и не спрашивать вовсе;
//   • имя без хеша (мини-апп: /app/assets/index.js, index.html, sw.js,
//     манифесты) — под тем же адресом завтра лежит другое содержимое, поэтому
//     ревалидация обязательна. Хеш в имена мини-аппа добавлять НЕЛЬЗЯ: правило
//     №13 CLAUDE.md (у параллельных PR расходились имена файлов, и git ловил
//     конфликт rename/rename, который content-драйвер не чинит).

const YEAR_S = 31_536_000;

/** Год жизни без единого обращения к серверу — только для иммутабельных имён. */
export const IMMUTABLE = `public, max-age=${YEAR_S}, immutable`;
/** Кэшировать можно, но использовать — только спросив (ETag/Last-Modified). */
export const REVALIDATE = 'public, no-cache';

// Хеш, который Vite ставит в имя: `-` + 8 символов base64url перед
// расширением (index-CTgJf44i.js, ModeMapLegend-CB-njDX_.js).
//
// Одной длины мало: `og-cover-v2.jpg` тоже даёт восемь символов после дефиса,
// а правят его под тем же именем — годовой кэш означал бы, что новая обложка
// не доедет до людей год. Поэтому дополнительно требуем СМЕСЬ РЕГИСТРОВ, как
// в настоящем выводе сборки: словарные хвосты («cover-v2», «web-app») её не
// дают. Ошибка возможна и здесь, но она смещена в безопасную сторону: хеш из
// одних строчных (~1% случаев) просто получит ревалидацию — медленнее, но
// не «пользователь не видит обновление».
const ASSET_EXT = '(js|css|woff2?|png|jpg|jpeg|svg|webp|avif|ttf|otf)';
const HASH_TAIL = new RegExp(`-([A-Za-z0-9_-]{8,})\\.${ASSET_EXT}$`);
const hasMixedCase = (s: string): boolean => /[A-Z]/.test(s) && /[a-z]/.test(s);

// Обновление приложения не должно залипать: воркер и манифест читаются
// браузером в обход обычного кэша только если мы сами не велели их держать.
const NEVER_IMMUTABLE =
  /(^|\/)(sw\.js|registerSW\.js|manifest\.webmanifest|[^/]*\.html)$/;

/** Какой Cache-Control отдать для файла статики по его пути. */
export function cacheControlFor(filePath: string): string {
  if (NEVER_IMMUTABLE.test(filePath)) return REVALIDATE;
  const tail = HASH_TAIL.exec(filePath)?.[1];
  return tail && hasMixedCase(tail) ? IMMUTABLE : REVALIDATE;
}
