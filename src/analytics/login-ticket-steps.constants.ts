// Шаги пути входа по билету (meta.step события login_ticket_step).
//
// Одно имя события с шагом внутри, а не шесть отдельных имён: так воронка
// считается одним GROUP BY, а в allow-list и санитайзере появляется одна
// запись вместо шести (приём onboarding_step).
//
// Отдельным файлом — analytics.constants.ts уже сверх лимита размера и обязан
// таять, а не расти вместе со списками (правило №10).

export const LOGIN_TICKET_STEPS = [
  /** Приложение попросило код. Это ПОКАЗ экрана входа, а не намерение: билет
   *  выписывается автоматически при открытии, и повтор по «попробовать снова»
   *  тоже считается. Строить на нём главную долю нельзя. */
  'issued',
  /** Человек открыл ссылку в боте и увидел карточку сверки. Существует только
   *  на телеграм-пути: Google/VK/почта подтверждаются в браузере и сюда не
   *  заходят. Поэтому шаг стоит ОТДЕЛЬНОЙ строкой, а не ступенью воронки —
   *  иначе «подтвердили» регулярно оказывалось бы больше «открыли». */
  'bot_opened',
  /** Вход подтверждён — билет получил хозяина. Пишут все способы входа. */
  'confirmed',
  /** «Это не я»: человек отказал. Механика сработала, это не сбой. */
  'denied',
  /** Код открыли или нажали, когда он уже мёртв (истёк, использован, отклонён). */
  'too_late',
  /** Приложение забрало сессию. Единственный шаг, означающий «человек внутри». */
  'taken',
] as const;
export type LoginTicketStep = (typeof LOGIN_TICKET_STEPS)[number];

/** Где открыт контейнер, попросивший билет. Тот же набор, что у StartTicketDto. */
export const LOGIN_TICKET_HOSTS = ['web', 'telegram', 'max'] as const;
export type LoginTicketHost = (typeof LOGIN_TICKET_HOSTS)[number];
