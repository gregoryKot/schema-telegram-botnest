// meta: тексты связей и опыт схем — клиническая запись, id клиента и свободный
// текст в событие не попадают (правило №7). Блок в /stats — src/bot/concept-graph-metrics.*.
//
//   concept_graph_open    — открыл схему случая по модели режимов.
//   concept_mode_linked   — заполнил связи режима (схемы, потребности, истоки).
//   concept_schema_linked — записал убеждение / детский опыт / потребности схемы.
//   concept_canvas_open   — перенёс схему случая на холст: из неё создана новая
