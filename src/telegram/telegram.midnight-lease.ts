// Окна полуночного обхода (аренда `midnightPlanner`): доделка оборванного
// прогона и захват пропущенной полуночи при старте процесса.
//
// Аренда тика в 00:00 — на LEASE_WINDOW.hourly: она отсекает только второй
// инстанс той же полуночи. Раньше и тик, и старт брали её на 23 ч, и захват
// при старте отнимал у тика следующие сутки: старт в 23:30 UTC (тик в 00:00
// видел аренду моложе 23 ч) или поздний старт после пропущенной полночи
// (захват в 05:00 → отказ тику через 19 ч). Обход идёт с now = момент старта,
// и для людей в UTC и западнее местный день к 23:xx уже спланирован —
// следующий им не планировал никто (docs/open/backend.md, 2026-10).
//
// Теперь старт захватывает обход, только если прошлый начат раньше сегодняшней
// 00:00 UTC (обхода этих суток не было), и не захватывает в последний час до
// полуночи — это сделает тик. Захват старта не позже 23:00, а окно тика 50 мин:
// тик в 00:00 его всегда пропускает.

/**
 * Сколько после начала оборванного прогона его ещё доделывать. Доделка идёт с
 * `now = runAt`, и время отправки, которое к старту уже прошло, очередь
 * отправляет на ближайшем тике. Доделка через 20 часов дала бы человеку
 * «сегодняшнее» напоминание за пару часов до завтрашнего — поэтому окно 6 ч,
 * а не сутки. Позже доделки нет: остаток — до полуночи, и его
 * видит проба cronLeases (2 ч, cron-lease-done.ts).
 */
export const RESUME_WINDOW_MS = 6 * 3_600_000;

const DAY_MS = 24 * 3_600_000;
/** За сколько до 00:00 UTC старт уже не захватывает обход: его сделает тик.
 * Больше окна аренды тика (LEASE_WINDOW.hourly) — иначе захват старта снова
 * отнял бы у тика следующие сутки. */
export const CATCH_UP_CUTOFF_MS = 3_600_000;
/** Тик, выстреливший на миг раньше 00:00, — всё равно обход этих суток. */
export const EARLY_TICK_SLACK_MS = 5 * 60_000;

/**
 * Окно `claimRun` для пропущенной полуночи при старте: захват пройдёт, только
 * если прошлый прогон начат раньше сегодняшней 00:00 UTC (с допуском на ранний
 * тик). null — до полуночи не больше CATCH_UP_CUTOFF_MS, захватывать нельзя.
 */
export function catchUpClaimWindowMs(at: Date): number | null {
  const sinceMidnight = at.getTime() % DAY_MS;
  if (DAY_MS - sinceMidnight <= CATCH_UP_CUTOFF_MS) return null;
  return sinceMidnight + EARLY_TICK_SLACK_MS;
}
