import { AddressForm, t } from '../notification/address-form';
import type { Letter } from './email.letters';

// Письмо привязки адреса к УЖЕ существующему аккаунту (purpose=link_email_auth).
// Раньше уходил loginLetter «Войти в…», и человек, которому чужой аккаунт
// привязал его адрес, кликал «войти» — а действие на деле было другим (аудит
// 2026-10, A3). Здесь прямо сказано, что делает ссылка, и что делать, если
// запрос не твой.
export function linkEmailLetter(form: AddressForm, link: string): Letter {
  return {
    subject: 'Привязать адрес к аккаунту «Всё по схеме»',
    body: t(
      form,
      `Перейди по ссылке, чтобы привязать этот адрес к своему аккаунту в «Всё по схеме». Открывай её в том же браузере, где уже открыт твой аккаунт.\n\n${link}\n\nСсылка действует 30 минут. Если запрос не от тебя — не переходи по ссылке, просто удали письмо.`,
      `Перейдите по ссылке, чтобы привязать этот адрес к своему аккаунту в «Всё по схеме». Открывайте её в том же браузере, где уже открыт ваш аккаунт.\n\n${link}\n\nСсылка действует 30 минут. Если запрос не от вас — не переходите по ссылке, просто удалите письмо.`,
    ),
  };
}
