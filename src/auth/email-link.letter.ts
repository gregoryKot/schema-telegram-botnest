import { AddressForm, t } from '../notification/address-form';
import type { Letter } from './email.letters';
import { emailLinkCodeForLink, showEmailLinkCode } from './email-link-code';

// Письмо привязки адреса к УЖЕ существующему аккаунту (purpose=link_email_auth):
// не «Войти» (аудит 2026-10, A3) — сказано, что делают код и ссылка. Код — для
// экрана, где привязку запросили (ссылка там не поможет, email-link-code.ts).
export function linkEmailLetter(form: AddressForm, link: string): Letter {
  const code = showEmailLinkCode(emailLinkCodeForLink(link));
  return {
    subject: 'Привязать адрес к аккаунту «Всё по схеме»',
    body: t(
      form,
      `Код, чтобы привязать этот адрес к своему аккаунту во «Всё по схеме»: ${code}\n\nВведи его на экране, где была запрошена привязка. Или перейди по ссылке — она сработает в том же браузере, где уже открыт твой аккаунт.\n\n${link}\n\nКод и ссылка действуют 30 минут. Если запрос не от тебя — не переходи по ссылке и никому не сообщай код, просто удали письмо.`,
      `Код, чтобы привязать этот адрес к своему аккаунту во «Всё по схеме»: ${code}\n\nВведите его на экране, где была запрошена привязка. Или перейдите по ссылке — она сработает в том же браузере, где уже открыт ваш аккаунт.\n\n${link}\n\nКод и ссылка действуют 30 минут. Если запрос не от вас — не переходите по ссылке и никому не сообщайте код, просто удалите письмо.`,
    ),
  };
}
