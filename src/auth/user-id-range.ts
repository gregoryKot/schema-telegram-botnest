// Диапазон userId. Единственное место, где живут эти числа: их спрашивают и
// выдача id новому веб-аккаунту (auth.service), и адресация уведомлений
// (bot/account.service), и спека auth.service.spec — вторая копия числа
// означала бы, что после первой же правки диапазона они разъедутся.
//
// Как так вышло. Для телеграм-входа userId буквально РАВЕН telegramId — так
// исторически сложилось ради совместимости с данными бота. Для всех остальных
// способов входа (Google, почта, VK, MAX) номер выдаётся из диапазона ниже,
// заведомо не пересекающегося с телеграмными (те около 1e9–1e10).
export const WEB_USER_ID_MIN = 1_000_000_000_000_000n;
export const WEB_USER_ID_MAX = 9_000_000_000_000_000n;

/** Номер выдан веб-входом — чата в Telegram по нему быть не может. */
export function isWebUserId(id: bigint): boolean {
  return id >= WEB_USER_ID_MIN;
}

/**
 * Номер сам по себе является адресом в Telegram. Верно для тех, кто пришёл
 * через бота и кому строку AuthProvider никогда не заводили (её создаёт вход
 * в мини-апп или на сайте) — таких большинство, и они обязаны продолжать
 * получать уведомления.
 */
export function isTelegramUserId(id: bigint): boolean {
  return !isWebUserId(id);
}
