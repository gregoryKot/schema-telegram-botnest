// Код отказа из query колбэка OAuth (`?error=…`) — в текст error(), а значит
// в DM владельцу. Значение присылает браузер, то есть кто угодно (S21, аудит
// 2026-11): после S13 таких DM до трёх в минуту, но сырой параметр позволял
// вписать в сообщение владельцу произвольный текст и ссылки. Коды провайдеров
// (access_denied, invalid_request, server_error, …) — строчные латинские слова
// через подчёркивание; всё прочее (массив из повторённого параметра, пробелы,
// URL, кириллица, длинное) сводится к «unknown».
const CODE_RE = /^[a-z_]{1,40}$/;

export function oauthErrorCode(raw: unknown): string {
  return typeof raw === 'string' && CODE_RE.test(raw) ? raw : 'unknown';
}
