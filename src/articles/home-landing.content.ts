// Текст продуктового лендинга schemehappens.ru («Всё по схеме») — один
// источник для двух читателей:
//   • человек: сайт рисует его в webapp/src/pages/ProductLandingPage.tsx
//     (вид — эмодзи, цвет, номер шага — в landing/productContent.ts по `id`);
//   • робот без JS: home-seo.render.ts собирает из него HTML, а
//     home-seo.middleware.ts вкладывает его в #root главной (GEO.md, «Главная
//     для робота пуста»). Яндекс JS почти не исполняет, у ботов нейросетей
//     бюджет на рендер не гарантирован.
//
// Почему файл в src/, а не в shared/: бэкенд не импортирует shared (rootDir
// ./src, см. src/booking/client-timezone.ts), а сайт импортирует из любого
// места репозитория. Поэтому здесь только строки: ни импортов, ни JSX, ни
// цветов — модуль обязан собираться и Nest, и Vite. Второй копии текста нет,
// сверять нечего: правишь строку здесь — меняются и страница, и HTML робота.
//
// Ссылка внутри текста — сегмент { text, href }: сайт рисует её своим <a>
// (с трекингом клика на сайт практики), сервер — обычной ссылкой.

