// Самоописание автора в статике вне `src/` — под ПИНОМ, а не под регэкспом.
//
// Свип 2026-09 вычистил «схема-терапевта» и «психолога» из продукта, но две
// строки нашёл владелец глазами, а не проверка: `jobTitle` в JSON-LD
// («Консультант по схема-терапии») и шапка `llms.txt` («Сайт специалиста по
// психологическому консультированию в подходе схема-терапии»). Оба —
// титул-существительное: подход выдаётся за квалификацию, которой нет.
//
// Почему пин, а не паттерн в check-robot-phrases.mjs: регэксп на
// «консультант»/«специалист» красил бы законные «обратитесь к специалисту»,
// «со специалистом в подходе схема-терапия» и «психологическое
// консультирование» (юридически точное название услуги, ФЗ-323) по всему
// продукту — ровно тот ложный долг, из-за которого гейты перестают работать
// (правило №15). Класс ловится не в словах, а в МЕСТЕ: самоописание живёт в
// двух конкретных полях, и они меняются раз в год. Поменял — значит принял
// решение осознанно: обнови пин и правило в docs/VOICE.md в том же PR.
//
// Правило — CLAUDE.md, раздел №12 («самоназвание») и docs/VOICE.md.
import { readFileSync } from 'fs';
import { join, resolve } from 'path';

const ROOT = resolve(__dirname, '..', '..', '..');

/** Утверждённая владельцем формула: глагол вместо звания. */
const APPROVED_JOB_TITLE = 'Веду практику в подходе схема-терапии';
const APPROVED_LLMS_LEAD =
  'Веду практику в подходе схема-терапии и КПТ. Онлайн.';

const INDEX_HTML = 'webapp/index.html';
const LLMS_TXT = 'webapp/public/llms.txt';

function read(rel: string): string {
  return readFileSync(join(ROOT, rel), 'utf8');
}

describe('самоописание автора в статике', () => {
  it(`${INDEX_HTML}: jobTitle в JSON-LD — утверждённая формула, а не звание`, () => {
    const m = /"jobTitle":\s*"([^"]*)"/.exec(read(INDEX_HTML));
    expect(m).not.toBeNull();
    expect(m?.[1]).toBe(APPROVED_JOB_TITLE);
  });

  it(`${LLMS_TXT}: первая строка-описание — та же формула`, () => {
    const lead = read(LLMS_TXT)
      .split('\n')
      .find((l) => l.startsWith('> '));
    expect(lead).toBe(`> ${APPROVED_LLMS_LEAD}`);
  });

  // Тот же запрет, что у паттернов samonazvanie-* в check-robot-phrases.mjs,
  // но по готовому файлу: подстава «Схема-терапевт» в JSON-LD обязана падать
  // и здесь, даже если кто-то вынесет статику из SCAN_FILES гейта.
  it.each([INDEX_HTML, LLMS_TXT])('%s: слова «схема-терапевт» нет', (rel) => {
    expect(read(rel)).not.toMatch(/схема-?терапевт/i);
  });

  // Титул-существительное о себе. Список узкий и только про самоописание:
  // «психологическое консультирование» как НАЗВАНИЕ УСЛУГИ законно и остаётся
  // (serviceType в JSON-LD, оговорка про ФЗ-323) — поэтому проверяются
  // конкретные конструкции «консультант/специалист по …», а не сами слова.
  it.each([INDEX_HTML, LLMS_TXT])(
    '%s: нет «консультант/специалист по …»',
    (rel) => {
      expect(read(rel)).not.toMatch(/(?:консультант|специалист)[а-я]*\s+по\s/i);
    },
  );
});
