// Указатель на PR или ветку, который умирает после мержа, — под ПИНОМ.
//
// Класс: документ пишут в PR и ссылаются на него словами «в этом PR» или
// именем ветки («ветка `claude/fix-…`»). После squash-мержа ветка удалена, а
// «этот PR» не значит ничего: следующий читатель не знает, о каком из
// семисот PR речь. Правило: ссылка на работу — номер (#123), он живёт вечно
// и открывается в один клик. Свип 2026-10 нашёл восемь таких мест в живых
// реестрах и шесть ячеек «Починка: этот PR» в docs/INCIDENTS.md (чинил #643).
//
// Почему пин, а не гейт на весь `docs/`: просматриваются только ЖИВЫЕ
// реестры — документы, по которым следующий агент начинает работу:
// docs/INCIDENTS.md, docs/README.md («Что осталось открытым»),
// docs/AUDIT_2026-10.md и docs/AUDIT_2026-10_FINDINGS.md. Исторические
// аудиты (docs/AUDIT_2026-08-12 и соседи, docs/archive/) — записи своего
// времени: «в этом PR» в них описывает момент написания, и переписывать
// историю задним числом незачем. Их эти пины НЕ сканируют.
//
// Что считается мёртвым указателем:
//   - «этот/этим/этом/этого/этому PR» отдельным словом, если сразу за ним нет
//     « (#123)» (с номером указатель живой) и фраза не стоит внутри «…» —
//     там цитата текста находки («Починка: этот PR»), а не указатель;
//   - ветка `claude/<имя>` в обратных кавычках или «ветка claude/<имя>».
//     Маска `claude/*` (счёт веток на origin) — не имя ветки и не считается;
//   - PR, названный веткой без префикса («PR `fix-x`») или заголовком
//     («PR «…»») вместо номера; «PR #631 «…»» — живой, номер стоит первым.
//
// Правило №15: у каждого исключения здесь есть образец, который оно гасит, И
// контрольный образец — похожий, но незаконный случай обязан краснеть.
import { readFileSync } from 'fs';
import { join, resolve } from 'path';

const ROOT = resolve(__dirname, '..', '..', '..');

/** Живые реестры: каждый файл обязан содержать якорь (проверка, что сканируем настоящий текст). */
const LIVE_REGISTRIES: ReadonlyArray<readonly [file: string, anchor: string]> =
  [
    ['docs/INCIDENTS.md', 'Реестр инцидентов'],
    ['docs/README.md', 'Что осталось открытым'],
    ['docs/AUDIT_2026-10.md', 'Глобальный аудит, 2026-10-11'],
    ['docs/AUDIT_2026-10_FINDINGS.md', 'находки по темам'],
  ];

// Цитата внутри «…» — текст находки или чужая формулировка, не указатель.
const QUOTED = /«[^»]*»/g;
// Перед «эт…» — не буква: иначе «поэтому PR» (в нём «этому PR») краснело бы.
// После «PR» — номер в скобках делает указатель живым: «этим PR (#128)».
const THIS_PR =
  /(?<![А-Яа-яЁё])эт(?:от|им|ом|ого|ому)\s+PR(?![A-Za-z])(?!\s\(#\d+\))/iu;
// Имя ветки: после «claude/» буква или цифра, поэтому маска `claude/*` и
// многоточие «claude/…» не считаются.
const BRANCH =
  /`claude\/[A-Za-z0-9][^`\s]*`|ветк[а-я]*\s+`?claude\/[A-Za-z0-9]/iu;
// PR, названный веткой без префикса («PR `fix-x`») или заголовком («PR «…»»)
// вместо номера: «PR #631 «…»» живой, номер стоит перед заголовком.
const NAMED_PR = /PR\s+(?:`(?:claude\/)?[a-z0-9]+-[A-Za-z0-9-]*`|«)/u;

/** Строки текста, содержащие мёртвый указатель: «номер строки: начало строки». */
export function deadPointers(text: string): string[] {
  const found: string[] = [];
  text.split('\n').forEach((line, i) => {
    if (
      THIS_PR.test(line.replace(QUOTED, '')) ||
      BRANCH.test(line) ||
      NAMED_PR.test(line)
    ) {
      found.push(`${i + 1}: ${line.trim().slice(0, 100)}`);
    }
  });
  return found;
}

function read(rel: string): string {
  return readFileSync(join(ROOT, rel), 'utf8');
}

describe('живые реестры без мёртвых указателей на PR и ветки', () => {
  it.each(LIVE_REGISTRIES)(
    '%s: нет «этот PR» без номера и имён веток claude/…',
    (file) => {
      expect(deadPointers(read(file))).toEqual([]);
    },
  );

  // Контроль, что скан читает настоящие файлы: пустой или подменённый файл
  // дал бы зелёное «ничего не найдено» и ничего не доказал бы.
  it.each(LIVE_REGISTRIES)(
    '%s: непустой, якорь «%s» на месте',
    (file, anchor) => {
      const text = read(file);
      expect(text.length).toBeGreaterThan(1000);
      expect(text).toContain(anchor);
    },
  );
});

describe('deadPointers: образцы и контрольные образцы', () => {
  it.each([
    ['в этом PR', 'этом PR'],
    ['Починка: этот PR', 'этот PR без кавычек'],
    ['Этот PR закрыл класс', 'заглавная буква'],
    ['правка этим PR.', 'этим PR перед точкой'],
    ['решено этого PR', 'этого PR'],
    ['(ветка `claude/fix-x`)', 'ветка в обратных кавычках'],
    ['`claude/fix-x`', 'имя ветки без слова «ветка»'],
    ['ветка claude/fix-x закрыта', 'ветка без обратных кавычек'],
    ['«Починка: этот PR», а правка — в этом PR', 'цитата не прячет остальное'],
    ['Закрыто: код в PR `fix-miniapp-url-defaults`', 'ветка без префикса'],
    ['Закрыто (PR «write-env: ручки»)', 'заголовок вместо номера'],
  ])('красное: %s (%s)', (text) => {
    expect(deadPointers(text)).toHaveLength(1);
  });

  it.each([
    [
      'поэтому PR мини-аппа после пересборки',
      '«поэтому PR» содержит «этому PR»',
    ],
    ['этим PR (#128)', 'номер в скобках делает указатель живым'],
    ['«Починка: этот PR» вместо номеров', 'цитата текста находки'],
    ['145 `claude/*` и 15 `dependabot/*`', 'маска веток, а не имя'],
    ['ветка claude/… удалена', 'многоточие вместо имени'],
    ['в #643 и PR #128', 'номер вместо указателя'],
    ['PR #631 «Бэкапы Amvera» открыт', 'номер перед заголовком'],
    ['Заполняется в том же PR, что и починка', 'не «этот PR»'],
  ])('зелёное: %s (%s)', (text) => {
    expect(deadPointers(text)).toEqual([]);
  });

  it('номер в скобках гасит указатель только сразу за «PR»', () => {
    // Контроль к «этим PR (#128)»: номер не рядом — указатель по-прежнему мёртв.
    expect(deadPointers('в этом PR, см. (#128)')).toHaveLength(1);
  });

  it('сообщает номер строки и не склеивает строки', () => {
    const found = deadPointers('чисто\nв этом PR\nчисто\n`claude/fix-y`');
    expect(found).toHaveLength(2);
    expect(found[0]).toMatch(/^2: /);
    expect(found[1]).toMatch(/^4: /);
  });
});
