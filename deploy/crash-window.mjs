// Счётчик падений приложения в скользящем окне времени (супервизор старта,
// deploy/entrypoint.mjs).
//
// Раньше счётчик обнулял любой прогон дольше минуты: приложение, падающее
// каждые 61 с, вечно жило на «fails=1/3», лимит не наступал, пауза между
// сериями не включалась, а каждый круг слал владельцу DM о старте (аудит
// 2026-10, находка «Супервизор контейнера»). Теперь считаются падения за
// последние windowMs, сколько бы ни длился каждый прогон: три падения за
// окно — лимит, техработы и растущая пауза (app-exit.mjs, superviseSeries).
// Падение реже окна (раз в полчаса при окне 15 мин) — не крашлуп, прод не
// паркуется.

/** Метки падений, попавшие в окно [now - windowMs, now], включая текущую. */
export function crashesInWindow(times, now, windowMs) {
  return [...times, now].filter((t) => now - t < windowMs);
}

/**
 * Окно из env: не число, ноль или отрицательное → значение по умолчанию.
 * Без проверки `STARTUP_CRASH_WINDOW_MS=abc` дал бы NaN, `now - t < NaN`
 * всегда ложно — и вечный крашлуп вернулся бы через опечатку в панели.
 */
export function validWindowMs(raw, def) {
  const n = Number(raw);
  return raw !== undefined && raw !== '' && Number.isFinite(n) && n > 0
    ? n
    : def;
}
