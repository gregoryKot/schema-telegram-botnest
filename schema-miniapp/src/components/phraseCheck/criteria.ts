// Девять примет, по которым разбирается фраза внутреннего голоса — построчно
// таблица «разрушительная самокритика ↔ помогающая самокоррекция». Разница
// между критиком и заботой не в строгости: у них разные цель, позиция,
// направленность, движущая сила, отношение к сделанному и к ошибкам, точность
// и ответ на вопрос «от чего зависит ценность человека».
//
// Формулировки безличные, поэтому вилки tr('ты','вы') здесь нет — обращение
// живёт в самом листе (PhraseCheck.tsx).
//
// id продублированы на бэкенде (src/bot/phrase-check.constants.ts) — он
// валидирует присланное и считает разбивку для /stats. Паритет держат два
// теста: criteria.test.ts здесь и phrase-check.service.spec.ts там.

