// Приметы, по которым разбирается фраза внутреннего голоса. Взяты из таблицы
// «разрушительная самокритика ↔ помогающая самокоррекция»: разница не в
// строгости, а в четырёх вещах — про поступок речь или про личность, что
// движет (желание или страх), насколько точна формулировка и что остаётся
// после неё.
//
// Формулировки безличные, поэтому вилки tr('ты','вы') здесь нет — обращение
// живёт в самом листе (PhraseCheck.tsx).
//
// id продублированы на бэкенде (src/bot/phrase-check.constants.ts) — он
// валидирует присланное и считает разбивку для /stats. Паритет держат два
// теста: criteria.test.ts здесь и phrase-check.service.spec.ts там.

export type PhraseMarkId = 'person' | 'fear' | 'absolute' | 'shame';

export interface PhraseCriterion {
  id: PhraseMarkId;
  emoji: string;
  /** Вопрос к фразе — короткий, на один экран */
  question: string;
  /** Так звучит забота о себе */
  care: string;
  /** Так звучит критик */
  critic: string;
  /** Зачем эта примета — одна строка под вариантами */
  why: string;
}

