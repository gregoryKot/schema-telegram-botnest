import { memo, useRef, type ReactNode } from 'react';

// Однажды открытая вкладка остаётся смонтированной и прячется display:none —
// возврат к ней это переключение видимости (~1 кадр), а не перемонтирование.
//
// Родилось из замера 2026-08-24 (CPU 6x, профиль телефона): каждый тап по
// вкладке размонтировал старую секцию и строил новую с нуля — ~100мс мёртвого
// времени + мигание скелетоном + повторный тяжёлый коммит, на каждом
// переключении, даже «тёплом» (жалоба владельца «стало хуже»: скелетон-кадр
// из #422 моргал при каждом тапе). Скелетон остаётся только там, где ему
// место — при ПЕРВОМ открытии вкладки (LazySections.useFirstPaintDone теперь
// срабатывает один раз за сессию: маунт один).
//
// СКРЫТАЯ ВКЛАДКА ЗАМОРОЖЕНА (замер на телефоне владельца 2026-08-26, панель
// PerfHud): без заморозки каждый setState в App — смена вкладки, приезд
// каждого фонового запроса — перерисовывал ВСЕ смонтированные вкладки разом,
// и тап по уже собранной вкладке стоил секунды («Помощь: экран 2989мс,
// показ»). Memo-гейт пропускает рендер поддерева, пока active=false: свежие
// пропсы вкладка получает одним рендером в момент показа. Следствие —
// refreshKey-рефетчи скрытых вкладок больше не проходят фоном, а срабатывают
// при показе: короткая свежесть-на-возврате вместо секундных блоков потока.
// Внутреннее состояние скрытой вкладки живёт как жило: memo режет только
// перерисовку сверху, собственные setState/эффекты компонента работают.
//
// Ленивые по вьюпорту куски (HeatmapCard через IntersectionObserver) в
// display:none не грузятся — и не должны. prerender=true собирает вкладку
// скрытой ЗАРАНЕЕ (usePrerenderSections), и даже ПЕРВЫЙ тап — переключение
// видимости. Без этого «ничего не поменялось» (владелец, 2026-08-24):
// keep-mounted ускорял только возвраты, а болело первое открытие.
const FrozenWhenHidden = memo(
  ({ children }: { active: boolean; children: ReactNode }) => <>{children}</>,
  // true = «пропсы равны», рендер пропускается. Скрытая вкладка не
  // перерисовывается; активная перерисовывается всегда.
  (_prev, next) => !next.active,
);

export function KeepMountedSection({
  active,
  prerender = false,
  children,
}: {
  active: boolean;
  prerender?: boolean;
  children: ReactNode;
}) {
  const wasActive = useRef(false);
  if (active || prerender) wasActive.current = true;
  if (!wasActive.current) return null;
  return (
    <div style={active ? undefined : { display: 'none' }} hidden={!active}>
      <FrozenWhenHidden active={active}>{children}</FrozenWhenHidden>
    </div>
  );
}
