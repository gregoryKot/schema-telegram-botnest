/**
 * Абзац «зачем это делать и через сколько виден результат». Его показывает и
 * AboutSheet, и экран входа в браузере (LoginScreen) — правило онбординга
 * CLAUDE.md требует ответить на «зачем» до первого действия, а третью
 * формулировку плодить нельзя.
 *
 * Отдельным именем, а не индексом в массиве ниже: обращение вида
 * `buildAboutText(tr)[2]` молча подменило бы текст, стоит вставить соседний
 * абзац — и заодно потеряло бы форму обращения, потому что из всех абзацев
 * она различается только у этого.
 */
export const buildWhyItWorks = (tr: (ty: string, vy: string) => string) =>
  tr(
    'Поведенческая техника: ты оцениваешь не фоновое ощущение, а конкретные действия дня — было ли что-то, что удовлетворило потребность. Через 3–5 дней паттерн начинает читаться: что тебя питает, что истощает, чего не хватает.',
    'Поведенческая техника: вы оцениваете не фоновое ощущение, а конкретные действия дня — было ли что-то, что удовлетворило потребность. Через 3–5 дней паттерн начинает читаться: что вас питает, что истощает, чего не хватает.',
  );

export const buildAboutText = (tr: (ty: string, vy: string) => string) => [
  'Бывает, что день прошёл нормально — а внутри что-то не так. Или наоборот, всё объективно сложно, но ощущение живое и устойчивое.',
  'Дело почти всегда в потребностях. Когда они удовлетворены — есть устойчивость. Когда нет — появляется тревога, раздражение, пустота.',
  buildWhyItWorks(tr),
  'Осознанно организовывать свою жизнь — видеть, что на самом деле происходит.',
];

export function getAboutText(form: AddressForm) {
  return buildAboutText((ty, vy) => (form === 'vy' ? vy : ty));
}

export function useAboutText() {
  return getAboutText(useAddressForm());
}

