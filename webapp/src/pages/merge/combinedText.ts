import { useTr } from '../../utils/addressForm';
import { pluralRu } from '../../../../shared/src/utils/pluralRu';

// R3 (аудит 2026-11): записи с одним ключом в обоих аккаунтах (заметка и
// благодарности за день, карточка схемы или режима, безопасное место, итог
// теста) не переезжают рядом дублем и не пропадают, а объединяются с записями
// текущего аккаунта (src/auth/merge-combine.ts). Число приходит с сервера
// (merge/preview → combined); пока оно больше нуля, экран не обещает «всё
// переедет» и говорит, что станет с такими записями.

type Tr = (ty: string, vy: string) => string;

/** Абзац про объединение; null — совпадающих записей нет. */
export function combinedText(n: number, tr: Tr): string | null {
  if (n <= 0) return null;
  const records = `${n} ${pluralRu(n, 'запись', 'записи', 'записей')}`;
  const match = pluralRu(n, 'совпадает', 'совпадают', 'совпадают');
  return (
    `${records} ${match} с ${tr('твоими', 'вашими')} по дню, схеме или режиму – каждая такая пара объединится в одну. ` +
    'Заметки и благодарности за день сложатся, в карточках схем и режимов заполнятся только пустые поля, ' +
    'у безопасного места и теста останется более свежая версия, а прежний результат теста сохранится в истории.'
  );
}

/**
 * Тексты сводки: `moves` — первая фраза («всё переедет» — только когда
 * объединять нечего), `combined` — абзац про объединение или null.
 */
export function useMergeTexts(combined: number): { moves: string; combined: string | null } {
  const tr = useTr();
  const moves = combined > 0
    ? tr('Если объединить – записи из него переедут в твой текущий аккаунт.', 'Если объединить – записи из него переедут в ваш текущий аккаунт.')
    : tr('Если объединить – всё, что в нём записано, переедет в твой текущий аккаунт.', 'Если объединить – всё, что в нём записано, переедет в ваш текущий аккаунт.');
  return { moves, combined: combinedText(combined, tr) };
}
