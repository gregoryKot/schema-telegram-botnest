// Тексты для ?error= после перехода по ссылке привязки почты из письма
// (бэкенд: src/auth/email-callback-redirect.ts). Нет сообщения — null.
export function emailLinkErrorMessage(
  code: string | null,
  tr: (ty: string, vy: string) => string,
): string | null {
  // Переход по ссылке на занятый адрес. Раньше он уводил на экран «ссылка
  // истекла» — неправда: ссылка жива, занят адрес.
  if (code === 'email_taken')
    return tr(
      'Этот адрес уже привязан к другому аккаунту. Войди по нему на странице входа — или привяжи сюда другой адрес.',
      'Этот адрес уже привязан к другому аккаунту. Войдите по нему на странице входа — или привяжите сюда другой адрес.',
    );
  // Ссылка привязки работает только в браузере, где открыт этот же аккаунт
  // (аудит 2026-10, A3): иначе чужой запрос привязал бы адрес не туда.
  if (code === 'email_link_session')
    return tr(
      'Ссылка привязки работает только в том браузере, где открыт твой аккаунт. Открой её там — или запроси письмо заново в настройках аккаунта.',
      'Ссылка привязки работает только в том браузере, где открыт ваш аккаунт. Откройте её там — или запросите письмо заново в настройках аккаунта.',
    );
  return null;
}
