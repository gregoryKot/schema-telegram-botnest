// Край листа-героя входа (AuthCut.tsx): срез ножницами в два слоя, как у полос лендинга
// (PaperBand), только сбоку на компьютере и снизу на телефоне. Одни точки на обе стороны:
// `along` — вдоль края (0…1200), `out` — насколько лист выходит за край (0…24). Нижний слой
// выглядывает из-под верхнего неравномерно, изломы не совпадают — подложенный лист, а не обводка.
type Pt = readonly [along: number, out: number];

const UNDER: readonly Pt[] = [[0, 21], [60, 18], [125, 24], [350, 13], [500, 23], [640, 16], [750, 13], [860, 21], [1085, 14], [1200, 17]];
const TOP: readonly Pt[] = [[0, 13], [150, 17], [320, 9], [530, 16], [720, 8], [890, 15], [1050, 9], [1200, 14]];

/** Контур слоя: от края листа (0) наружу по точкам и обратно; `side` — справа или снизу от листа. */
export function cutPath(layer: 'under' | 'top', side: 'right' | 'bottom'): string {
  const pts = layer === 'under' ? UNDER : TOP;
  const xy = ([along, out]: Pt) => (side === 'right' ? `${out} ${along}` : `${along} ${out}`);
  return `M0 0 L${pts.map(xy).join(' L')} L${side === 'right' ? '0 1200' : '1200 0'} Z`;
}

/** Холст среза: 24 поперёк края, 1200 вдоль. */
export const cutViewBox = (side: 'right' | 'bottom') => (side === 'right' ? '0 0 24 1200' : '0 0 1200 24');
