import { useTr } from '../../utils/addressForm';
import { botHandle, botUrl } from '../../utils/botConfig';

// Вход через Google и через Telegram на сайте убран в 2026-11 (запрос
// Роскомнадзора: пользователей из России нельзя авторизовать через иностранный
// сервис). Кнопок больше нет, а люди, входившие только так, остались — без
// подсказки человек решит, что аккаунт пропал. Одна компонента на оба случая
// (правило №3), стоит под «Войти по email» и видна сразу.
//   Google: аккаунт находится по той же почте (src/auth/email-login-user.ts).
//   Telegram: аккаунт открывается внутри Telegram; там в «Аккаунте» добавляют
//   почту (кодом из письма — src/auth/email-link-code.ts) или VK ID и дальше
//   входят ими на сайте. Ссылка ведёт в чат бота — это не вход.
// Безродно в обеих формах: «вход был», а не «входил».
export function LoginFormerNote() {
  const tr = useTr();
  return (
    <>
      <p className="al-note" data-testid="login-telegram-note">
        {tr('Раньше вход был через Telegram? Открой приложение в боте ', 'Раньше вход был через Telegram? Откройте приложение в боте ')}
        <a href={botUrl} target="_blank" rel="noopener noreferrer">{botHandle}</a>
        {tr(
          ': в профиле — «Аккаунт и привязки», добавь там почту или VK ID и входи ими на сайте. Записи на месте.',
          ': в профиле — «Аккаунт и привязки», добавьте там почту или VK ID и входите ими на сайте. Записи на месте.',
        )}
      </p>
      <p className="al-note" data-testid="login-google-note">
        {tr(
          'Раньше вход был через Google? Войди по email с той же почтой — пришлём ссылку. Аккаунт и записи на месте.',
          'Раньше вход был через Google? Войдите по email с той же почтой — пришлём ссылку. Аккаунт и записи на месте.',
        )}
      </p>
    </>
  );
}
