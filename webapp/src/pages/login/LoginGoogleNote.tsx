import { useTr } from '../../utils/addressForm';

// Вход через Google убран в 2026-11 (запрос Роскомнадзора: пользователей из
// России нельзя авторизовать через иностранный сервис). Кнопки больше нет, а
// люди, входившие только через Google, остались: их аккаунт находится по той
// же почте (src/auth/email-login-user.ts). Подсказка стоит под «Войти по
// email» и видна сразу — без неё человек решит, что аккаунт пропал.
// Безродно в обеих формах: «вход был», а не «входил».
export function LoginGoogleNote() {
  const tr = useTr();
  return (
    <p className="al-note" data-testid="login-google-note">
      {tr(
        'Раньше вход был через Google? Войди по email с той же почтой — пришлём ссылку. Аккаунт и записи на месте.',
        'Раньше вход был через Google? Войдите по email с той же почтой — пришлём ссылку. Аккаунт и записи на месте.',
      )}
    </p>
  );
}
