// Неразрывные пробелы лендинга (typo.ts): тире не начинает строку, короткое слово не
// висит в конце строки, короткое название в кавычках не рвётся; слова не меняются.
import { describe, it, expect } from 'vitest';
import { glue } from './typo';
import { HOME_HERO, HOME_FINAL, HOME_HEADINGS } from '../../../../src/articles/home-landing.content';

const NB = '\u00a0';
const plain = (s: string) => s.replace(/\u00a0/g, ' ');

describe('glue: неразрывные пробелы лендинга', () => {
  it('пробел перед « — » неразрывный, после — обычный', () => {
    expect(glue('Первый шаг — просто заметить')).toBe(`Первый шаг${NB}— просто заметить`);
  });

  it('после предлога, союза и числа пробел неразрывный; после длинного слова — обычный', () => {
    expect(glue('бережно, в вашем темпе')).toBe(`бережно, в${NB}вашем темпе`);
    expect(glue('бесплатно · без рекламы')).toBe(`бесплатно · без${NB}рекламы`);
    expect(glue('встреча 15 минут')).toBe(`встреча 15${NB}минут`);
    expect(glue('тревога и самокритика')).toBe(`тревога и${NB}самокритика`);
    // после знака препинания перенос разрешён: «а,» — уже не висячий союз
    expect(glue('а, может')).toBe('а, может');
  });

  it('цепочка коротких слов склеивается целиком, без пропусков', () => {
    expect(glue('и в вашем')).toBe(`и${NB}в${NB}вашем`);
  });

  it('короткое название в кавычках — одной строкой, длинная цитата — нет', () => {
    expect(glue('«Всё по схеме» — бесплатное')).toBe(`«Всё${NB}по${NB}схеме»${NB}— бесплатное`);
    expect(glue('к «какая схема включилась»')).toBe(`к${NB}«какая схема включилась»`);
  });

  it('тексты лендинга: слова те же, тире не начинает строку', () => {
    for (const s of [HOME_HERO.lead, HOME_FINAL.title, HOME_FINAL.text, ...Object.values(HOME_HEADINGS)]) {
      const g = glue(s);
      expect(plain(g)).toBe(plain(s));
      expect(g).not.toMatch(/ —/);
    }
    expect(glue(HOME_HERO.lead)).toContain(`«Всё${NB}по${NB}схеме»${NB}—`);
  });
});
