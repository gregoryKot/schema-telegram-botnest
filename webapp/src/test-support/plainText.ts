// Текст элемента с обычными пробелами вместо неразрывных. Строки примитивов склеиваются при отрисовке (glue,
// shared/src/utils/typo.ts: PaperAlert, DoneSheet, лента «Записей») — короткое слово держится со следующим
// неразрывным пробелом, и `textContent` с фразой через обычный пробел не совпадает. Проверка по фразе не должна
// зависеть от склейки; что склейка есть, проверяет тест самого примитива (PaperAlert.test.tsx).
export const plainText = (el: Element | null | undefined): string => (el?.textContent ?? '').replace(/\u00a0/g, ' ');
