import { useTr } from '../utils/addressForm';
import { WarnNote } from './WarnNote';

// Единственная копия предупреждения о потере второго фактора при объединении
// аккаунтов. Показывают ОБА экрана, которые реально зовут merge.merge():
// /account/merge (MergePage) и привязка мессенджера (LinkDevicePage).
// Почему компонент, а не строка на каждой странице: копипаста четырёх длинных
// строк (ты/вы × два экрана) разъехалась бы при первой правке (правила №3/№11).
export function TwoFactorLossNote() {
  const tr = useTr();
  return (
    <WarnNote>
      {tr(
        'Двухфакторная защита второго аккаунта не переедет. После объединения вход будет без кода – включи её заново в настройках.',
        'Двухфакторная защита второго аккаунта не переедет. После объединения вход будет без кода – включите её заново в настройках.',
      )}
    </WarnNote>
  );
}
