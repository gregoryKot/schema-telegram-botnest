import { glue } from '../../../../shared/src/utils/typo';

/** Заголовки моста: общий glue и точечно — «это» не висит ни в конце строки («Нести это / в одиночку…»), ни в начале
 *  («…Нести / это в одиночку»): трёхбуквенные слова glue не клеит, строка-источник не меняется — пробелы вокруг
 *  «это» неразрывные при отрисовке, «Нести это в одиночку» держится одной строкой. */
export function glueBridge(text: string): string {
  return glue(text).replace(/ (это) /gi, '\u00a0$1\u00a0');
}
