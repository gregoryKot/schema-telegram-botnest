import type { ModeNodeData } from './nodeStyle';

// Нейтральная бумага фигуры холста (ревью вкуса b34): «поведение» — не сущность с оттенком, а то,
// что человек делает. Его лист — бумага страницы с серым контуром, а не шестой цвет рядом с режимами.
// Числа — готовыми значениями (экспорт картинкой переменных не знает, см. paperInk в nodePaper.ts):
// тёплый серый бумаги приложения, почти без хромы.

/** Типы фигур без своего оттенка. */
const PLAIN_TYPES = new Set(['behavior']);

/** Фигура на нейтральной бумаге: тип без оттенка и цвет вручную не выбран (выбран — лист этого цвета). */
export const isPlainPaper = (type: string, d: Pick<ModeNodeData, 'customColor'>): boolean =>
  PLAIN_TYPES.has(type) && !d.customColor;

/** Оттенок-подпись для `--h` у нейтральной фигуры: тёплая бумага страницы. */
export const PLAIN_HUE = 85;

/** [L C] лица, контура и тени нейтральной бумаги в трёх состояниях заливки (как TONES в nodePaper.ts). */
export const PLAIN_TONES = {
  paper: ['0.965 0.006', '0.7 0.012', '0.87 0.008'],
  filled: ['0.91 0.008', '0.7 0.012', '0.82 0.01'],
  full: ['0.5 0.012', '0.42 0.012', '0.78 0.01'],
} as const;
