/**
 * Заголовок и текст экрана подтверждённой брони (`BookingConfirmedView`).
 * «Оплата прошла» и чек — только при `paid` (вебхук оплаты поставил `paidAt`):
 * вводная INTRO_15 бесплатна и подтверждается лично, а сессия в валюте без
 * онлайн-оплаты подтверждается сразу и оплачивается по договорённости, как
 * обещает `doneCostNote` (аудит 2026-10).
 */
export function confirmedCopy(b: { type: string; paid: boolean }): { title: string; text: string } {
  if (b.type === 'INTRO_15') {
    return {
      title: 'Знакомство записано',
      text: 'Знакомство бесплатное, оплаты и чека не будет. Подтвержу встречу лично по контакту из заявки – без подтверждения она не состоится.',
    };
  }
  if (b.paid) return { title: 'Оплата прошла', text: 'Встреча подтверждена. Чек придёт от «Мой налог».' };
  return { title: 'Встреча подтверждена', text: 'Об оплате напишу перед встречей.' };
}
