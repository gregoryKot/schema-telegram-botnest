// Плашка «нет сети» для мобильной вёрстки: верхняя панель с индикатором
// «офлайн» на узком экране скрыта (index.css), и человек не знал, почему
// оценки не уходят. Текст, без спиннера; на десктопе плашка скрыта — там
// индикатор в topbar. Текст безличный, вилка ты/вы не нужна.
export function OfflineBanner({ offline }: { offline: boolean }) {
  if (!offline) return null;
  return (
    <div className="offline-banner" role="status">
      Нет сети. Оценки сохранятся на устройстве и отправятся, когда сеть вернётся.
    </div>
  );
}
