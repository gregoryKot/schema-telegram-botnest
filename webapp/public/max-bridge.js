// Загрузчик моста MAX. Отдельным файлом, а не инлайном в странице: у нас
// script-src 'self' без unsafe-inline, и инлайн-скрипт CSP просто заблокирует
// (ровно на это наступил зонд max-probe — см. историю webapp/public/max-probe.js).
//
// Мост подключаем ТОЛЬКО внутри MAX. Их скрипт создаёт глобальный объект
// window.WebApp — имя настолько общее, что грузить его всегда нельзя: в обычном
// браузере объект появился бы на пустом месте, и приложение решило бы, что
// открыто в мессенджере.
//
// Признак MAX виден до загрузки моста: площадка передаёт стартовые параметры
// фрагментом URL (#WebAppData=…), оттуда же их читает и сам мост.
(function () {
  if (window.location.hash.indexOf('WebAppData=') === -1) return;
  // document.write, а не appendChild: скрипт обязан выполниться ДО модуля
  // приложения — хост спрашивают на первом же экране, и асинхронная загрузка
  // означала бы, что первый рендер считает себя браузером.
  document.write(
    '<script src="https://st.max.ru/js/max-web-app.js"><\/script>',
  );
})();
