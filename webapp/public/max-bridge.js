// Загрузчик моста MAX. Отдельным файлом, а не инлайном в странице: у нас
// script-src 'self' без unsafe-inline, и инлайн-скрипт CSP просто заблокирует
// (ровно на это наступил зонд max-probe — см. историю webapp/public/max-probe.js).
//
// Мост подключаем ТОЛЬКО внутри MAX. Их скрипт создаёт глобальный объект
// window.WebApp — имя настолько общее, что грузить его всегда нельзя: в обычном
// браузере объект появился бы на пустом месте, и приложение решило бы, что
// открыто в мессенджере.
//
// Признак MAX виден до загрузки моста: площадка передаёт стартовые параметры
// фрагментом URL (#WebAppData=…), оттуда же их читает и сам мост.
//
// Мало одного ключа: значение обязано иметь форму initData MAX — внутри
// непустые `hash` и `auth_date`. Иначе ссылка `…/app/#WebAppData=x` в любом
// браузере подгружала бы мост, приложение считало себя MAX, слало `x` как
// подпись и ловило 401 с алертом владельцу на каждый клик (аудит 2026-10, E-5).
// Подпись всё равно проверяет сервер; здесь — только отсев не-MAX запусков.
// Зеркало этой проверки — shared/src/host/maxLaunchShape.ts.
//
// Параметр сверяется ЦЕЛИКОМ, от начала фрагмента или после «&». Поиск
// подстроки здесь ловил чужой параметр: Telegram передаёт свои стартовые
// данные тем же фрагментом — `#tgWebAppData=…`, и внутри этого имени
// подстрока `WebAppData=` есть. Из-за этого мост MAX грузился у КАЖДОГО
// пользователя Telegram, создавал window.WebApp, приложение считало себя
// открытым в MAX, отправляло пустую MAX-подпись и показывало «Не удалось
// войти» (инцидент 2026-08-08).
(function () {
  // Внутри функции, а не глобально: страница делит область имён с мостом MAX
  // и телеграмным SDK, лишних глобалей тут быть не должно.
  var MAX_LAUNCH_PARAM = /(?:^|[#&])WebAppData=([^&]*)/;
  var found = MAX_LAUNCH_PARAM.exec(window.location.hash);
  if (!found) return;
  var initData;
  try {
    // Один слой кодирования, как снимает его и само приложение.
    initData = decodeURIComponent(found[1]);
  } catch (e) {
    return;
  }
  // Ключи — целиком и с непустым значением: `xhash=1` не `hash`.
  if (!/(^|&)hash=[^&]/.test(initData) || !/(^|&)auth_date=[^&]/.test(initData)) return;
  // document.write, а не appendChild: скрипт обязан выполниться ДО модуля
  // приложения — хост спрашивают на первом же экране, и асинхронная загрузка
  // означала бы, что первый рендер считает себя браузером.
  document.write(
    '<script src="https://st.max.ru/js/max-web-app.js"><\/script>',
  );
})();
