-- Статус «связь завершена» (backend#33, аудит 2026-10-11): отказ от роли
-- терапевта переводит его связи в `ended`, а не оставляет активными.
--
-- Значение enum и его использование нельзя делать в одной транзакции
-- (Postgres: «unsafe use of new value»), поэтому бэкфил лежит в следующей
-- миграции. IF NOT EXISTS — повторный прогон после падения безопасен.
ALTER TYPE "RelationStatus" ADD VALUE IF NOT EXISTS 'ended';
