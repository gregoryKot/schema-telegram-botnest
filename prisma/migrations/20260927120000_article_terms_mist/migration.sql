-- Терминологическая сверка с МИСТ (docs/TERMINOLOGY.md, свип 2026-09-27).
-- Затрагивает только статьи, живущие ИСКЛЮЧИТЕЛЬНО в проде (созданы через
-- админку, их нет в src/articles/articles.seed.ts, поэтому ArticlesService
-- их не переcидит) — 'schematerapia-vda' и 'zdoroviy-vzrosliy-bez-terapii'.
-- Проверено содержимое обеих статей на проде (curl /api/articles/<slug>):
-- 'zdoroviy-vzrosliy-bez-terapii' уже написана в каноничных терминах
-- («Схема-терапия», «Здоровый Взрослый») и правки не требует — запись на
-- неё не заводится, чтобы UPDATE не выполнялся вхолостую.
--
-- 'schematerapia-vda' написана без дефиса («Схематерапия»/«схематерапия»/
-- «схематерапию») и содержит устаревшее название схемы «Подчинение»
-- (МИСТ: «Покорность») и разнорегистрое название режима «здоровый
-- взрослый» (МИСТ: оба слова с заглавной — «Здоровый Взрослый»).
--
-- REPLACE(text, from, to) идемпотентен по построению: после первого
-- прогона искомая подстрока уже отсутствует, повторный migrate deploy
-- не меняет строку ещё раз.
UPDATE "Article"
SET
  "title" = REPLACE("title", 'Схематерапия', 'Схема-терапия'),
  "description" = REPLACE("description", 'схематерапия', 'схема-терапия'),
  "content" = REPLACE(
    REPLACE(
      REPLACE(
        REPLACE(
          REPLACE(
            "content",
            'Схематерапия', 'Схема-терапия'
          ),
          'схематерапию', 'схема-терапию'
        ),
        'схематерапия', 'схема-терапия'
      ),
      'схема подчинения', 'схема покорности'
    ),
    'здоровый взрослый', 'Здоровый Взрослый'
  ),
  "updatedAt" = CURRENT_TIMESTAMP
WHERE "slug" = 'schematerapia-vda';
