-- Аудит 2026-10 (D-10): события кризисной карточки («показана», «нажали на
-- телефон доверия») раньше писались с userId — в БД лежал список людей, у
-- которых был кризис. Новые события пишутся анонимно (anonymous-events.constants.ts),
-- эта миграция обезличивает уже накопленные строки.
--
-- Данные-only: схема не меняется. Идемпотентна — повторный прогон не находит
-- строк с userId и ничего не трогает. Агрегаты /stats (по name/meta) не
-- затрагиваются, исчезает только связь «событие → человек».
UPDATE "AnalyticsEvent"
SET "userId" = NULL
WHERE "name" IN ('crisis_card_shown', 'crisis_hotline_tapped')
  AND "userId" IS NOT NULL;
