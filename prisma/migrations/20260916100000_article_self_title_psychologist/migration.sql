-- «в работе со схема-терапевтом» → «в работе со специалистом в подходе
-- схема-терапия» (docs/VOICE.md, свип 2026-09). «Схема-терапевт» называет
-- специальность, которой нет: схема-терапия — подход, а не квалификация.
--
-- Почему миграция, а не только правка src/articles/articles.seed.ts: сид
-- вставляется ТОЛЬКО в пустую таблицу («inserts these only if the table is
-- empty» — чтобы не затирать правки из админки), поэтому на проде статья уже
-- лежит со старым текстом и правка исходника до читателя не доезжает. Тот же
-- урок, что с пулом канала «Здоровый Взрослый» (CLAUDE.md).
--
-- Идемпотентно: REPLACE меняет строку, только если подстрока в ней есть, а
-- WHERE отсекает статьи без неё (повторный прогон и прогон на пустой БД —
-- no-op). "updatedAt" проставляется явно: колонка NOT NULL без DEFAULT
-- (Prisma @updatedAt ставит значение на клиенте) — инцидент 2026-07-16.

UPDATE "Article"
SET "content" = REPLACE(
      "content",
      'в работе со схема-терапевтом',
      'в работе со специалистом в подходе схема-терапия'
    ),
    "updatedAt" = CURRENT_TIMESTAMP
WHERE "content" LIKE '%в работе со схема-терапевтом%';
