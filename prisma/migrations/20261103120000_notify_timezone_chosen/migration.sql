-- Пояс уведомлений выбран человеком руками или стоит по умолчанию (QA
-- 2026-11-03). С этой миграцией /api/init записывает в notifyTimezone пояс
-- устройства, пока человек не выбрал свой сам: иначе «сегодня» сервера (серия,
-- недельная полоса, напоминания) жило по Москве у любого клиента. Признак
-- нужен отдельной колонкой: значение по умолчанию ('Europe/Moscow') нельзя
-- отличить от осознанно выбранной Москвы, а человек во Владивостоке, выбравший
-- московское время, иначе получал бы свой пояс обратно при каждом входе.
--
-- Бэкфил: пояс, отличный от Москвы, до этой миграции мог появиться только
-- руками (кнопки бота, настройки сайта и мини-аппа, перенос при слиянии
-- аккаунтов): /api/init пояс не записывал — фронты слали число tzOffset,
-- которое валидатор отбрасывал. Московские строки остаются false: для них
-- выбор не отличить от умолчания, пояс подтянется с устройства.
-- Идемпотентно целиком: колонка и бэкфил — в одном блоке, повторный прогон
-- колонку уже видит и строки не трогает (иначе он пометил бы выбранными и
-- пояса, взятые с устройства уже после первой выкладки).
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'User'
      AND column_name = 'notifyTimezoneChosen'
  ) THEN
    ALTER TABLE "User" ADD COLUMN "notifyTimezoneChosen" BOOLEAN NOT NULL DEFAULT false;
    UPDATE "User" SET "notifyTimezoneChosen" = true
    WHERE "notifyTimezone" <> 'Europe/Moscow';
  END IF;
END $$;
