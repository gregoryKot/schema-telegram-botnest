-- Замер планов на синтетике горизонта роста (docs/PERF_PLANS.md) показал, что
-- индекса по одной колонке `date` (аудит M2, миграция 20260813060000) мало:
-- строки он находил, а `userId` всё равно читался из таблицы, и
-- `COUNT(DISTINCT "userId") WHERE date = $1` трогал 9402 страницы за 70 мс.
-- Со второй колонкой тот же запрос идёт Index Only Scan: 33 страницы, 2 мс.
--
-- Индекс ЗАМЕНЯЕТСЯ, а не добавляется: `date` — ведущая колонка, поэтому
-- `[date, userId]` обслуживает всё, что обслуживал `[date]`. Третий индекс на
-- самой растущей таблице означал бы лишнюю запись на каждый INSERT оценки.
--
-- Порядок (создать → удалить), а не наоборот: между шагами таблица ни секунды
-- не остаётся без индекса под этот фильтр.
--
-- Обычный CREATE INDEX, не CONCURRENTLY: CONCURRENTLY не работает внутри
-- транзакции, которой Prisma оборачивает миграцию, а падение такого шага
-- оставляет инвалидный индекс и P3009 — то есть крашлуп прода
-- (CLAUDE.md, «Миграции БД», инцидент 2026-07-16).

-- CreateIndex
CREATE INDEX "Rating_date_userId_idx" ON "Rating"("date", "userId");

-- DropIndex
DROP INDEX "Rating_date_idx";
