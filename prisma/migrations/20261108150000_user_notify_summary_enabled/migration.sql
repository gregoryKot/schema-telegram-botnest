-- R2 (аудит 2026-11, решение владельца Р1): два тумблера уведомлений.
-- «Напоминания» — прежний "notifyEnabled" (полуночный планировщик, парный
-- триггер); «Итоги дня» — новая колонка: сводка после заполнения трекера,
-- вехи и «с возвращением». Раньше тумблер сайта «Итоги дня» висел на
-- "notifyEnabled": выключал напоминания, а итоги приходили всё равно.
--
-- Дефолт true у всех: итоги до этой миграции приходили каждому, кто заполнял
-- трекер, независимо от "notifyEnabled", — набор того, что человек получает,
-- не меняется; меняется только смысл тумблеров.
-- Идемпотентна: IF NOT EXISTS.
ALTER TABLE "User" ADD COLUMN IF NOT EXISTS "notifySummaryEnabled" BOOLEAN NOT NULL DEFAULT true;
