-- Booking.confirmEffectsDoneAt: побочные эффекты подтверждения (ссылка на
-- встречу, событие календаря, DM/письма админу) доведены до конца. Раньше они
-- шли после CAS HELD→CONFIRMED без отметки: падение БД или смерть пода в этом
-- окне оставляли CONFIRMED без ссылки и календаря, а повтор вебхука отвечал OK
-- без эффектов (глобальный аудит 2026-10-11, security#21). Пусто = эффекты ещё
-- не доделаны: их доводят повтор вебхука, ручное подтверждение и крон-добор.
ALTER TABLE "Booking" ADD COLUMN "confirmEffectsDoneAt" TIMESTAMP(3);

-- Бэкфил: подтверждённые и проведённые брони, у которых ссылка на встречу уже
-- записана, считаются доделанными. Без него крон-добор разослал бы по старым
-- броням повторные «Запись подтверждена». Брони CONFIRMED без ссылки остаются
-- пустыми — это и есть те, кого добор должен доделать. Идемпотентно: уже
-- проставленные не трогаются.
UPDATE "Booking"
SET "confirmEffectsDoneAt" = "updatedAt"
WHERE "confirmEffectsDoneAt" IS NULL
  AND "status" IN ('CONFIRMED', 'COMPLETED')
  AND "meetingUrl" IS NOT NULL;
