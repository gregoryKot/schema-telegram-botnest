-- Снятие застрявшей записи миграции после P3009. Исполняется entrypoint-ом
-- перед каждым `migrate deploy` (deploy/entrypoint.mjs, RECOVER_CMD) и вручную
-- (ops.sh: op=migrate-resolve-failed). Эквивалент `prisma migrate resolve
-- --rolled-back` для ЛЮБОЙ застрявшей записи, а не для двух имён из июля.
--
-- История: 2026-07-16 упала 20260716120000_healthy_adult_ai_pool (сырой INSERT
-- без updatedAt NOT NULL), 2026-07-18 — 20260717182526_analytics_events
-- (CREATE TABLE без IF NOT EXISTS, 42P07). В обоих случаях запись оставалась
-- с finished_at IS NULL, и `migrate deploy` отказывался применять что-либо
-- (P3009). Список имён в этом файле не масштабируется: следующая упавшая
-- миграция была бы третьей строкой, а откат VPS на образ, где её нет, не
-- поднялся бы вовсе (docs/AUDIT_2026-10_FINDINGS.md, infra#8).
--
-- ЧТО ЭТО ЗНАЧИТ ДЛЯ БАЗЫ. Prisma НЕ оборачивает миграцию в транзакцию
-- (замерено на Postgres 16: миграция из двух операторов, второй падает ->
-- первый остаётся в схеме, запись с finished_at IS NULL, applied_steps_count=0).
-- Удаление записи не откатывает этот огрызок, оно только разрешает Prisma
-- применить миграцию заново. Поэтому безопасность держится на правиле
-- CLAUDE.md, «Миграции БД», п. 3: миграции идемпотентны, и не только DDL
-- (IF NOT EXISTS), но и DML (INSERT ... WHERE NOT EXISTS; UPDATE, который
-- даёт тот же результат при повторе). Entrypoint зовёт этот файл при КАЖДОМ
-- старте контейнера, так что миграция, упавшая на втором операторе, будет
-- применяться заново на каждом рестарте. Идемпотентная — переживёт это.
-- Неидемпотентный DML (INSERT без WHERE NOT EXISTS, UPDATE ... SET n = n + 1)
-- перед падающим оператором повторит свою часть на каждом рестарте: задвоит
-- строки или сдвинет счётчик, пока человек не починит миграцию. Раньше P3009
-- держал базу до вмешательства человека, теперь этого стопора нет: поэтому
-- миграция, падающая посередине, обязана быть починена в день падения, а
-- правило п. 3 не рекомендация. Деструктивная миграция (DROP/RENAME уже
-- выполнился до падения) этим файлом НЕ лечится: образ предыдущего релиза
-- поднимется на новой схеме; восстановление — из бэкапа.
--
-- ЗАЩИТА ОТ ЖИВОЙ МИГРАЦИИ. Запись с finished_at IS NULL есть и у миграции,
-- которая прямо сейчас выполняется (второй под при перекатывающемся деплое,
-- медленный CREATE INDEX). Prisma на время migrate держит advisory-lock
-- 72707369 (замерено по pg_locks). Если он занят, миграция идёт, а не
-- застряла: ничего не удаляем. xact-вариант снимается сам в конце запроса,
-- поэтому замок не утекает в соединение.
--
-- Безопасно при повторном запуске: на здоровой БД записей с
-- finished_at IS NULL нет -> 0 строк. Имена в RETURNING печатает ops.sh;
-- больше ничего из таблицы выводить нельзя (логи Actions публичны, а logs
-- несёт тексты ошибок со значениями).
DELETE FROM "_prisma_migrations"
WHERE finished_at IS NULL
  AND rolled_back_at IS NULL
  AND pg_try_advisory_xact_lock(72707369)
RETURNING migration_name;
