#!/usr/bin/env node
// Правило гейта мужского рода по паре форм обращения (QA 2026-11): к движку
// check-gendered-forms.mjs, вынесено отдельным модулем (правило №10).
//
// Строчные PATTERNS ищут род рядом с местоимением: «ты сделал», «я устал». А
// вопрос трекера «Принимал ли ты… Действовал из своих ценностей…» и примеры
// «Сказал нет просьбе» местоимения перед глаголом не несут — подлежащее
// опущено или стоит после глагола, и гейт показывал 0. Зато у такой строки
// есть пара: tr('ты-вариант', 'вы-вариант'). Если вы-вариант ставит то же
// слово во множественное число («Сказал» → «Сказали»), слово согласовано с
// читателем, а значит в ты-варианте у него мужской род. Пара сама задаёт
// контекст, поэтому регэксп по одному слову не нужен и ложных срабатываний на
// «Партнёр сказал» нет: там вы-вариант тоже «сказал».

// Вызов с двумя строковыми литералами подряд: tr('…', '…'),
// t(form, '…', '…'), pickForm(form, '…', '…'). Литерал — '…', "…" или `…`.
const LIT = (n) => `(['"\`])((?:\\\\.|(?!\\${n})[^\\\\])*)\\${n}`;
const CALL = new RegExp(
  `(?<![\\w$.])(?:tr|t|pickForm)\\(\\s*(?:[\\w.]+\\s*,\\s*)?${LIT(1)}\\s*,\\s*${LIT(3)}`,
  'g',
);

// Мужской род без «-л»: краткие прилагательные и неправильное прошедшее.
// Значение — форма множественного числа, которую ищем в вы-варианте.
const IRREGULAR = {
  сам: 'сами',
  один: 'одни',
  готов: 'готовы',
  уверен: 'уверены',
  рад: 'рады',
  прав: 'правы',
  виноват: 'виноваты',
  обязан: 'обязаны',
  должен: 'должны',
  важен: 'важны',
  нужен: 'нужны',
  свободен: 'свободны',
  спокоен: 'спокойны',
  способен: 'способны',
  доволен: 'довольны',
  согласен: 'согласны',
  мог: 'могли',
  смог: 'смогли',
  помог: 'помогли',
  вырос: 'выросли',
  привык: 'привыкли',
};

const words = (s) => s.match(/[А-Яа-яЁё]+/g) ?? [];

/** Форма множественного числа для мужской формы слова или null. */
export function pluralOfMasculine(word) {
  const w = word.toLowerCase();
  if (IRREGULAR[w]) return IRREGULAR[w];
  if (/^[а-яё]{2,}лся$/.test(w)) return w.slice(0, -2) + 'ись'; // вернулся → вернулись
  if (/^[а-яё]{2,}[аяиеёыуо]л$/.test(w)) return w + 'и'; // сказал → сказали
  return null;
}

/** Мужские формы в ты-варианте, которые вы-вариант согласует с читателем. */
export function trPairHits(src) {
  const hits = [];
  CALL.lastIndex = 0;
  let m;
  while ((m = CALL.exec(src))) {
    const vy = new Set(words(m[4]).map((w) => w.toLowerCase()));
    // Строка ты-литерала (а не вызова): у tr(\n '…',\n '…') они разные.
    const line = src.slice(0, m.index + m[0].indexOf(m[1])).split('\n').length;
    for (const w of words(m[2])) {
      const plural = pluralOfMasculine(w);
      if (plural && vy.has(plural)) hits.push({ line, word: w, plural });
    }
  }
  return hits;
}
