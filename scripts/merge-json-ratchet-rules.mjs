// Как merge-json-ratchet.mjs сводит лист, который сдвинули ОБЕ стороны.
// Вынесено из драйвера, чтобы он не рос (правило №10), а исключения по ключам
// лежали на виду, рядом с причиной.
//
// Режим файла выбирает .gitattributes (правило №13):
//   ratchet-max — больше лучше и метрика не складывается (покрытие, mutation):
//                 берём лучшее из двух;
//   ratchet-min — меньше лучше и метрика не складывается (страницы планов
//                 запросов, нарушения axe по правилам) — и реестры со
//                 строками-причинами, где чисел нет;
//   ratchet-sum — счётчик, который складывается по непересекающимся правкам:
//                 строки файла, байты всего JS, нарушения в файле. Слитое дерево
//                 весит базу плюс оба сдвига, поэтому планка — та же сумма:
//                 base + (ours − base) + (theirs − base), отрицательные дельты
//                 тоже (одна сторона ужала, другая дописала).
//
// Почему не min для счётчиков (2026-11-06, шесть параллельных веток): обе
// стороны дописали по блоку в `src/bot/stats-sections.ts` (123→128 и 123→125,
// слитый файл — 130), min ставил 125, и CI краснел «файл вырос»; так же терялся
// рост `webapp:total-js` (#898, #930). В обратную сторону min молча терял
// прогресс: 4→3 и 4→2 разными починками дают на дереве 1, а планка оставалась 2.
//
// Где сумма ошибается и почему это терпимо: обе стороны починили ОДНО и то же
// место (одинаковый ханк) — сумма строже дерева, гейт краснеет громко, лечится
// `--update` своего гейта. Тихого ослабления планки сумма не даёт, кроме
// частично повторённой правки (вишня одного коммита в обе ветки) — редкость.

/**
 * Ключи sum-файла, для которых сумма бессмысленна: путь файла (как %P у git)
 * → путь листа от корня JSON через точку → режим. Сверка с настоящими
 * бейслайнами и .gitattributes — `src/test-support/gates/merge-drivers.spec.ts`.
 */
export const KEY_MODES = {
  'scripts/bundle-size-baseline.json': {
    // Самый тяжёлый чанк — максимум по чанкам, а не сумма: две ветки, раздувшие
    // разные чанки, на слитом дереве дают max из двух, сумма приписала бы рост
    // одного чанка другому. Слепое место: обе стороны раздули ОДИН и тот же
    // самый тяжёлый чанк — max ниже дерева, гейт краснеет громко.
    'webapp:largest-chunk': 'max',
  },
};

export const MODES = ['min', 'max', 'sum'];

/** Режим листа: исключение из KEY_MODES (только в sum-файле) или режим файла. */
export function leafMode(fileMode, label, keyPath) {
  if (fileMode !== 'sum') return fileMode;
  return KEY_MODES[label]?.[keyPath] ?? fileMode;
}

/**
 * Значение листа-числа, который сдвинули обе стороны. `o` — значение у
 * предка, `undefined`, если ключ новый с обеих сторон. Возвращает `undefined`,
 * если однозначного ответа нет (драйвер отдаёт конфликт человеку).
 */
export function combineMoved(mode, o, a, b) {
  if (mode === 'max') return Math.max(a, b);
  if (mode === 'min') return Math.min(a, b);
  // Ключ родился в обеих ветках — один и тот же новый файл, созданный дважды.
  // Его содержимое сводит человек (add/add), складывать два «рождения» нечего:
  // берём больший замер, он не ниже ни одной из сторон.
  if (o === undefined) return Math.max(a, b);
  if (typeof o !== 'number') return undefined;
  // Счётчик не бывает отрицательным: две стороны, убравшие одно и то же,
  // дают сумму ниже нуля — на дереве там ноль.
  return Math.max(0, a + b - o);
}
