// Правило гейта мужского рода для статусных подписей о третьем лице, чей пол
// неизвестен: клиент в кабинете терапевта, партнёр по паре (аудит 2026-10).
// «активен сегодня», «был недавно», «не активен», «Ещё не заполнил»,
// «${name} ещё не заполнил дневник» — подписи короткие, подлежащего в них
// нет, поэтому правила про «ты»/«я» их не видят. Вынесено из
// gendered-forms-patterns.mjs: тот упёрся в храповик размера (правило №10).
//
// Закрытый список слов, а не PAST_M: на коротких литералах PAST_M шумит на
// существительных («Канал», «Раздел», «Сигнал», «Запрос»). «ответил» в список
// не входит — «${who} не ответил» про площадку (Google/VK), род её законный.
// Мужской род после существительного («Клиент ещё не заполнил карточки»)
// тоже законен (CLAUDE.md, «Род читателя») — ветки «после клиент/партнёр»
// здесь сознательно нет.
const ST =
  '(?:(?:[Нн]е|[Ее]щё\\s+не|[Уу]же)\\s+)?' +
  '(?:[Аа]ктивен|[Нн]еактивен|[Бб]ыл|[Зз]аходил|[Зз]аполнил|[Пп]одключился|' +
  '[Пп]рисоединился|[Пп]ропал|[Вв]ернулся|[Оо]тметил)(?![А-Яа-яЁё])';

// Ловит: статусное слово в НАЧАЛЕ короткого литерала (до 3 слов) — строка в
// кавычках, JSX-текст после `>` или на собственной строке; и форму
// «${имя} статусный-глагол». Длинная фраза («Был стабильный взрослый, которому
// можно было доверять») не ловится: после статусного слова больше двух слов.
export const STATUS_PATTERNS = [
  [
    'status-label-m',
    new RegExp(
      `(?:['"\`>]\\s*|^\\s*)${ST}(?:\\s+[^\\s'"\`<>{}]+){0,2}\\s*(?=['"\`<]|\\$\\{|$)` +
        `|\\$\\{[^}]+\\}\\s+${ST}`,
      'g',
    ),
  ],
];
