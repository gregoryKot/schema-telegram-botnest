#!/usr/bin/env node
// Правила гейта терминологии схема-терапии — режимы и группы режимов.
// Отделены от scripts/schema-terms-rules.mjs (схемы/домены/название метода)
// по правилу №10 CLAUDE.md: гейт, упёршийся в лимит размера, дробится на
// движок + модули правил, а не получает исключение из храповика. Движок
// (scripts/check-schema-terms.mjs) не знает про это разделение — он читает
// готовый RULES из schema-terms-rules.mjs, которая импортирует MODE_RULES
// отсюда и склеивает список.
//
// Эталон и принципы построения правил — см. шапку schema-terms-rules.mjs
// (документ АНИМА/МИСТ, docs/TERMINOLOGY.md, узкий якорь на реальный случай).
// Тест — src/test-support/gates/schema-terms.spec.ts (пинит образцом И
// контрольным образцом, правило №15 CLAUDE.md); песочница gate-sandbox.ts
// копирует этот файл вместе со schema-terms-rules.mjs как локальную
// зависимость (`from './schema-terms-modes.mjs'`).

// Редкое/специфичное слово или фраза: false-positive маловероятен, схема-
// контекст не нужен (в отличие от схемных правил в соседнем файле).
const GLOBAL_MODES = [
  [
    'disfunktsionalnye-roditeli',
    /Дисфункциональн(?:ые|ых|ым)\s+родител[а-яё]*/gu,
    'Критик',
    'Группу критикующих режимов называем «Критик», не «Дисфункциональные родители».',
  ],
  // «…Родитель» вместо «…Критик» — только с заглавной первой буквы.
  // «Наказывающий» здесь легитимен ТОЛЬКО как «Наказывающий Критик»
  // (допустимая альтернатива «Карающему Критику» в документе), но
  // «Наказывающий Родитель» остаётся запрещённым — это правило его и ловит.
  [
    'roditel-kritik',
    /(?:Карающ|Требовательн|Критикующ|Наказывающ)[а-яё]*\s+[Рр]одител[а-яё]*/gu,
    'Критик',
    'Критикующие режимы называются «…Критик» (Карающий/Требовательный/Внушающий Вину/Наказывающий), не «…Родитель».',
  ],
  [
    'dobryi-roditel',
    /(?<!\p{L})Добрый\s+Родитель(?!\p{L})/gu,
    'Хороший Родитель',
    'Здоровый режим называется «Хороший Родитель», не «Добрый Родитель».',
  ],
  [
    'zloy-rebenok',
    /(?:Злой|Злящийся|Злящаяся)\s+Реб[её]нок(?!\p{L})/gu,
    'Сердитый / Упрямый / Разъярённый Ребёнок',
    'Режим — «Сердитый»/«Упрямый»/«Разъярённый Ребёнок», не «Злой»/«Злящийся Ребёнок».',
  ],
  [
    'pokornyi-kapitulyant',
    /(?:Покорный|Уступчивый)\s+Капитулянт/gu,
    'Послушный / Беспомощный Капитулянт',
    'Режим — «Послушный»/«Беспомощный Капитулянт», не «Покорный»/«Уступчивый».',
  ],
  [
    'samouspokoitel',
    /Самоуспокоител[а-яё]*/gu,
    'Отстранённый Самоутешитель',
    'Режим — «Отстранённый Самоутешитель», не «Самоуспокоитель».',
  ],
  [
    'polianna',
    /(?<!\p{L})Полианна(?!\p{L})/gu,
    'Поллианна',
    'Пишется «Поллианна» — с двумя «л».',
  ],
  [
    'giperkompensator',
    /Гиперкомпенсатор[а-яё]*/gu,
    'Гиперкомпенсация',
    'Копинговая ГРУППА называется «Гиперкомпенсация» — режима «Гиперкомпенсатор» нет.',
  ],
];

// Вторая половина имени режима строчными буквами. Матчим ТОЛЬКО когда первое
// слово с заглавной (иначе ловим обычное «уязвимого ребёнка не бросили
// одного»).
const HALF_CAPITALIZED = [
  [
    'child-half-capitalized',
    /(?:Уязвим|Сердит|Счастлив|Импульсивн|Одинок|Покинут|Униженн|Упрям|Разъярённ|Недисциплинированн)[а-яё]*\s+ребён[а-яё]*/gu,
    'Ребёнок',
    'Второе слово названия режима — тоже с заглавной: «…Ребёнок».',
  ],
  [
    'healthy-adult-half-capitalized',
    /Здоров[а-яё]*\s+взросл[а-яё]*/gu,
    'Здоровый Взрослый',
    'Режим — «Здоровый Взрослый» (оба слова с заглавной).',
  ],
  [
    'detached-half-capitalized',
    /Отстранённ[а-яё]*\s+(?:защитник|самоутешител[а-яё]*)/gu,
    'Отстранённый Защитник / Отстранённый Самоутешитель',
    'Второе слово названия режима — тоже с заглавной.',
  ],
  [
    'critic-half-capitalized',
    /(?:Карающ|Требовательн|Внушающ)[а-яё]*\s+критик/gu,
    'Критик',
    'Второе слово названия режима — тоже с заглавной: «…Критик».',
  ],
];

// Экспорт ради schema-terms-rules.mjs (склеивает в общий RULES) и
// schema-terms.spec.ts (пинит образцом каждое правило через общий RULES).
export const MODE_RULES = [
  ...GLOBAL_MODES.map(([id, pattern, canonical, hint]) => ({ id, pattern, canonical, hint })),
  ...HALF_CAPITALIZED.map(([id, pattern, canonical, hint]) => ({
    id,
    pattern,
    canonical,
    hint,
  })),
];
