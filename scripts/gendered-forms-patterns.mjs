#!/usr/bin/env node
// Правила гейта мужского рода — вынесены из check-gendered-forms.mjs, чтобы
// движок (обход дерева, храповик, отчёт) не рос вместе со списком паттернов
// (правило №10: файл дробится, а не пухнет). Тест gendered-forms.spec.ts
// пинит каждый паттерн и каждое ALLOW-исключение своим образцом.

// \b в JS считает границей только ASCII, поэтому границы слова для кириллицы
// приходится задавать lookaround'ами.
const L = '(?<![А-Яа-яЁё])';
const R = '(?![А-Яа-яЁё])';
// «ог/ёг» намеренно НЕ здесь: они ловят существительные («я психолог»,
// «диалог»). Неправильные формы на согласный — отдельным списком ниже.
const PAST_M = '(?:ал|ял|ил|ел|ыл|ёл|ул|рос|ался|ился|ялся|улся|ёлся)';
const FILLER =
  '(?:не\\s+|бы\\s+|уже\\s+|сам\\s+|тогда\\s+|сегодня\\s+|снова\\s+|всё\\s+ещё\\s+)*';

// Экспорт ради gendered-forms.spec.ts — пинит каждый паттерн/ALLOW образцом.
export const PATTERNS = [
  // «ты сделал», «ты бы остался», «ты вернулся»
  ['ty-past', new RegExp(`${L}[Тт]ы\\s+${FILLER}[а-яё]+${PAST_M}${R}`, 'g')],
  [
    'bud-ty-past',
    new RegExp(`${L}бы\\s+ты\\s+${FILLER}[а-яё]+(?:л|лся|рос)${R}`, 'g'),
  ],
  [
    'ty-irregular',
    new RegExp(
      `${L}[Тт]ы\\s+${FILLER}(?:вырос|подрос|смог|мог|лёг|нёс|привык)${R}`,
      'g',
    ),
  ],
  // «ты не обязан», «ты готов», «ты живой»
  [
    'ty-short-adj',
    new RegExp(
      `${L}[Тт]ы\\s+${FILLER}(?:обязан|должен|готов|уверен|рад|спокоен|виноват|прав|свободен|живой|один)${R}`,
      'g',
    ),
  ],
  // Реплики от первого лица, которые пользователь произносит или примеряет
  // к себе: «скажи "я устал"», «ругаю себя: я плохой».
  ['ya-past', new RegExp(`${L}[Яя]\\s+${FILLER}[а-яё]+${PAST_M}${R}`, 'g')],
  [
    'ya-short-adj',
    new RegExp(
      `${L}[Яя]\\s+${FILLER}(?:рад|устал|плохой|виноват|должен|готов|один|слаб|сломан|недостоин|достоин|обязан|ценен|` +
        `уверен|способен|склонен|уязвим|занят|зол|спокоен|силён)${R}`,
      'g',
    ),
  ],
  // «Справлюсь сам», «останусь один» — «сам»/«один» как ЦЕЛЬ (не filler,
  // см. шапку файла) рядом с глаголом 1/2 лица, откуда бы ни взялся субъект —
  // явное «ты»/«я» или опущенное (конструкция сама несёт лицо в окончании).
  // «сам по себе» / «один раз» / «один из» исключены — это не про род.
  [
    'solo-verb-m',
    new RegExp(
      `${L}[А-Яа-яЁё]+(?:усь|юсь|ешься|ишься|ешь|ишь|у|ю)\\s+` +
        `(?:сам(?!\\s+по\\s+себе)|один(?!\\s+(?:раз|из)${R}))${R}`,
      'g',
    ),
  ],
  // «на себя самого», «горжусь собой самим» — усилительное «сам» в косвенном
  // падеже при возвратном местоимении. Не путать с «с самого начала» (там
  // «самого» относится не к «себя», а к следующему существительному).
  [
    'reflexive-samogo-m',
    new RegExp(`${L}(?:себя\\s+самого|собой\\s+самим)${R}`, 'g'),
  ],
  // «позволь себе быть сильным», «стать удобным», «чувствую себя маленьким»,
  // «оказаться недостаточным», «быть максимально продуктивным» — инфинитив
  // ИЛИ спрягаемая форма 1/2 лица + до 3 слов (наречие/отрицание) + краткое
  // прилагательное в творительном. Минимум 2 буквы основы перед «ым/им» —
  // иначе ловились бы местоимения «им»/«ним» («быть рядом с ним»).
  [
    'inf-adj-m',
    new RegExp(
      `${L}(?:быть|стать|казаться|остаться|оставаться|оказаться|показаться|выглядеть|` +
        `чувствовать\\s+себя|чувствую\\s+себя|чувствуешь\\s+себя)\\s+` +
        `(?:[а-яё-]+\\s+){0,3}[а-яё]{2,}(?:ым|им)${R}`,
      'g',
    ),
  ],
  // Читатель, названный уменьшительным прилагательным как существительным:
  // «Дорогой маленький я», «сказать себе-маленькому», «как маленькому,
  // которого не обнимали», «внутри — маленький и уязвимый». Прилагательное
  // при существительном («маленький шаг», «как ребёнку, которого») — законно
  // и сюда намеренно не попадает.
  [
    'child-self-m',
    new RegExp(
      `${L}(?:[Мм]аленьк(?:ий|ая)\\s+я${R}` +
        `|себе[-\\s]маленьк(?:ому|им)` +
        `|как\\s+маленьк(?:ому|им)\\s*[,.—–]` +
        `|—\\s*маленьк(?:ий|ая)\\s+и\\s+[а-яё]+(?:ый|ий|ая))`,
      'g',
    ),
  ],
  // Мужское прошедшее с ОПУЩЕННЫМ подлежащим — рассказ читателя о себе, где
  // «я»/«ты» не написано, и потому предыдущие правила его не видят:
  // «Научился прятать», «Выучил одно правило», «Привык молчать». Список
  // расширен свипом 2026-08 реальными пропусками, найденными вручную (не
  // только научение/привыкание — любое законченное действие «от себя»:
  // справился, подвёл, вырос, вернулся, устал…). Ловим только в начале фразы
  // (после точки, тире, двоеточия или открывающей кавычки) — при явном
  // подлежащем («Критик перестал», «отец привык») род принадлежит ему и
  // правило молчит.
  [
    'dropped-subject-past',
    new RegExp(
      `(?:^|[.!?—:]\\s+|[«"'(]\\s*)` +
        `(?:научился|выучил|усвоил|привык|запомнил|приучился|разучился|перестал|` +
        `подвёл|справился|облажался|отгородился|оставался|заслужил|интересовался|` +
        `вырос|вернулся|сделал|смог|устал)${R}`,
      'gi',
    ),
  ],
  // Скобочный костыль вместо живой формулировки: «сделал(а)», «должен(на)»
  ['brackets', new RegExp(`${L}[а-яё]+\\((?:а|на|ла|ась|ой|ая)\\)`, 'g')],
];

// Строки, где мужской род принадлежит не читателю, а другому существительному
// («живой человек», «стабильный взрослый»), либо автору сайта, который пишет
// о себе. Это законный мужской род — его переписывать нечего.
//
// Три записи ниже (articles.seed.ts × 2, landing/constants.ts × 1) — тоже
// автор о себе (Григорий, схема-терапевт, ведёт статьи и FAQ от первого лица),
// но НЕ по файлу целиком: надёжного структурного признака «это голос автора,
// а не читателя» у гейта нет — и статьи, и подсказки читателю лежат в одних
// и тех же `<p>`/строковых литералах, синтаксически неотличимых. Поэтому
// точечно, по конкретной фразе (см. CLAUDE.md, «Род читателя»: «мужской род
// автора сайта о себе — законный»).
export const ALLOW = [
  /живой\s+(?:человек|контакт)/i,
  /(?:оказывался|стабильный|здоровый|Здоровый|рядом)\s+взрослый/i,
  /Клиент\s+должен/i,
  /кто\s+должен\s+быть\s+близким/i,
  /нужно\s+любому/i,
  // «которое я создал» — приложение (ср. рода, отсюда «которое», не
  // «который») в landing/constants.ts. Прежняя запись ловила только
  // «который я создал», которого в коде нет ни разу — исправлено.
  /котор(?:ый|ое)\s+я\s+создал|я\s+схема-терапевт\s+и\s+сделал/i,
  /что\s+он\s+важен/i,
  /кто\s+готов\s+слушать/i,
  // articles.seed.ts: автор статьи размышляет о собственной клинической
  // практике от первого лица — не реплика, которую примеряет на себя читатель.
  /Я\s+бы\s+притормозил\s+с\s+глубинной\s+работой/,
  /[Зз]а\s+годы\s+практики\s+я\s+заметил/,
  // «подробнее об этом я писал в статье о травме…» — автор статьи ссылается
  // на свой же более ранний текст от первого лица, не реплика читателя.
  /об\s+этом\s+я\s+писал\s+в\s+статье/,
];
