// (легитимным) образцом, который краснеть не должен (правило №15).
//
// Многие запрещённые варианты — обычные слова русского языка вне схема-
// терапевтического контекста («неудача», «слияние», «подчинение силой»), либо
// формы, отличающиеся от канона на одну букву («Полианна»/«Поллианна»).
// Поэтому у каждого правила — самый узкий якорь, который ловит реальный
// случай (инцидент: «схема Неудача» вместо «Неуспешность»).
//
// SCHEMA_CTX — якорь для терминов, чья форма совпадает с обычным словом:
// нарушение засчитывается только когда термин выглядит НАЗВАНИЕМ (после
// «схема», внутри <strong>/<hN>, в кавычках/апострофах, сразу после «/>).
const SCHEMA_CTX =
  "(?:схем[а-яёА-ЯЁ]*\\s+«?" + // «схема «Неудача»», «схема Неудача»
  '|<strong>' + // <strong>Неудача
  '|<h[1-6]>(?:\\d+\\.?\\s*)?' + // <h3>9. Неудача
  "|[>«]" + // >Неудача<, «Подчинение и Самопожертвование»
  "|['\"])"; // 'Неудача', "Неудача"

/** Термин/фраза (без якоря), которую нужно проверять только в схема-контексте.
 * Правая граница (?!\p{L}) обязательна: без неё «Провал» матчился бы как
 * префикс обычного слова «Провалили» (найдено на реальном дереве —
 * articles.seed.ts, «Провалили презентацию» после `</h2>\n<p>`, то есть
 * якорь `>` сработал легитимно, а без границы справа схватил не то слово). */
function schemaNameRule(id, wordAlt, canonical, hint) {
  return {
    id,
    pattern: new RegExp(`${SCHEMA_CTX}(${wordAlt})(?!\\p{L})`, 'gu'),
    canonical,
    hint,
  };
}

