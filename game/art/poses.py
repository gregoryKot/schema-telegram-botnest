"""A2: три копинга кота, по 6 кадров 48x48 — та же плотность пикселя, что у
базового кота (код ставит позам масштаб игрока), чтобы поза не была «другим котом»."""
from cat import Pose, draw
from px import strip

G = 46  # линия пола в единицах

def stand(**kw):
    base = dict(
        legs_far=[[(31, 37), (32, 42), (32, G)], [(17, 37), (15, 42), (16, G)]],
        legs_near=[[(33, 37), (34, 42), (34, G)], [(20, 37), (19, 42), (20, G)]])
    base.update(kw)
    return Pose(**base)

def lunge():
    """FIGHT: замах, удар лапой, отдача — удар выматывает, а не радует."""
    f = []
    f.append(stand(body=(23, 37, 11, 5, 0.12), head=(35, 34, 5.8), ears=(0.6, 0.7),
                   legs_far=[[(31, 39), (35, 43), (33, G)], [(15, 38), (11, 43), (15, G)]],
                   legs_near=[[(33, 39), (37, 43), (36, G)], [(18, 39), (14, 43), (18, G)]],
                   tail=[(13, 36), (7, 37), (3, 39)]))
    f.append(stand(body=(22, 38, 11, 4.6, 0.2), head=(34, 36, 5.8), ears=(0.8, 0.9),
                   legs_far=[[(30, 40), (35, 44), (32, G)], [(14, 38), (9, 43), (14, G)]],
                   legs_near=[[(32, 40), (37, 44), (35, G)], [(17, 39), (12, 44), (17, G)]],
                   tail=[(12, 35), (7, 33), (3, 34)]))
    f.append(stand(body=(26, 34, 13, 4.6, -0.12), head=(39, 30, 5.8), ears=(0.7, 0.8),
                   legs_far=[[(33, 36), (38, 33), (42, 30)], [(15, 37), (11, 42), (9, G)]],
                   legs_near=[[(35, 37), (41, 35), (46, 33)], [(18, 38), (14, 42), (13, G)]],
                   tail=[(13, 35), (7, 33), (2, 32)],
                   streaks=[[(44, 29), (47, 31)], [(43, 38), (47, 38)]]))
    f.append(stand(body=(27, 35, 13, 4.8, 0.0), head=(39, 31, 5.8), ears=(0.7, 0.8),
                   legs_far=[[(34, 37), (38, 40), (37, G)], [(16, 38), (12, 42), (11, G)]],
                   legs_near=[[(36, 37), (42, 39), (45, 42)], [(19, 38), (15, 42), (15, G)]],
                   tail=[(14, 35), (8, 34), (3, 35)],
                   streaks=[[(46, 34), (47, 40)], [(44, 36), (45, 43)]]))
    f.append(stand(body=(24, 36, 11, 5, 0.06), head=(35, 32, 5.8), ears=(0.4, 0.5),
                   legs_far=[[(31, 38), (33, 42), (32, G)], [(16, 38), (13, 42), (15, G)]],
                   legs_near=[[(33, 38), (35, 42), (35, G)], [(19, 38), (16, 42), (18, G)]],
                   tail=[(13, 35), (8, 37), (5, 41)]))
    f.append(stand(body=(23, 36, 11, 5.2, 0.1), head=(34, 35, 5.8), ears=(0.3, 0.4),
                   eyes='half', tail=[(13, 36), (9, 40), (7, 44)]))
    return f

def appease():
    """FAWN: падает на бок и переворачивается брюхом вверх — сдаётся."""
    f = []
    f.append(stand(body=(24, 37, 11, 5, 0.08), head=(35, 34, 5.8), ears=(0.3, 0.3),
                   tail=[(13, 37), (9, 41), (6, 44)]))
    f.append(Pose(body=(25, 39, 12, 5.5, 0.15), head=(36, 37, 5.8), ears=(0.4, 0.4),
                  legs_far=[[(31, 41), (34, 44), (36, G)], [(17, 41), (13, 44), (14, G)]],
                  legs_near=[[(33, 42), (37, 44), (39, G)], [(20, 42), (16, 45), (18, G)]],
                  tail=[(13, 39), (8, 43), (5, 45)]))
    f.append(Pose(body=(24, 41, 13, 5, 0.0), head=(37, 40, 5.8), ears=(0.9, 0.9),
                  legs_far=[[(31, 43), (35, 41), (38, 38)], [(17, 43), (13, 41), (10, 39)]],
                  legs_near=[[(33, 41), (37, 38), (39, 35)], [(19, 41), (16, 37), (14, 35)]],
                  belly=(24, 40, 9, 2.5, 0.0), tail=[(11, 42), (6, 44), (2, 45)]))
    for i, (wig, eyes) in enumerate(((0, 'half'), (1, 'half'), (0, 'closed'))):
        f.append(Pose(body=(24, 41, 13, 5, 0.0), head=(37, 40 - wig * 0.5, 5.8), ears=(1.2, 1.2),
                      legs_far=[[(30, 39), (33, 34 + wig), (35, 31)], [(18, 39), (16, 34), (19, 31 + wig)]],
                      legs_near=[[(32, 38), (36, 34 - wig), (34, 30)], [(20, 38), (18, 33 + wig), (21, 30)]],
                      belly=(24, 38, 10, 3, 0.0), eyes=eyes,
                      tail=[(11, 42), (6, 44 - wig), (2, 44)]))
    return f

def freeze():
    """FREEZE: клубок, хвост на носу, уши прижаты, медленное дыхание."""
    f = []
    f.append(stand(body=(24, 38, 11, 5, 0.1), head=(34, 36, 5.6), ears=(0.6, 0.7),
                   tail=[(13, 38), (9, 42), (8, 45)]))
    f.append(Pose(body=(24, 40, 11, 5.5, 0.05), head=(33, 39, 5.6), ears=(0.9, 1.0),
                  legs_far=[[(29, 43), (31, 45), (33, G)], [(17, 43), (15, 45), (17, G)]],
                  legs_near=[[(31, 43), (34, 45), (36, G)], [(20, 43), (19, 45), (21, G)]],
                  tail=[(13, 40), (12, 45), (20, 46)]))
    for i, ry in enumerate((6.0, 6.0, 6.5, 6.0)):
        f.append(Pose(body=(20, 46 - ry, 11, ry, 0.0), head=(33, 40.5 - (ry - 6), 5.4),
                      ears=(0.5, 0.6), eyes='closed' if i else 'half', tail_front=True,
                      tail=[(10, 44), (20, 45.5), (31, 45.5), (38, 43)], tail_w=2.4))
    return f

SHEETS = {'cat_dash': lunge, 'cat_play': appease, 'cat_sleep': freeze}

def build():
    return {k: strip([draw(p, s=1, size=48) for p in fn()]) for k, fn in SHEETS.items()}
